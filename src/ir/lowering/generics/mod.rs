//! Generic monomorphization for GIR lowering.
//!
//! Walks the AST to discover all concrete generic instantiations (e.g., `Pair[int, str]`),
//! then creates monomorphized TypeDefs and Functions with substituted types.

mod substitute;

pub use substitute::{substitute_type_pub, substitute_function_body_pub, builtin_fault_enum};
use substitute::{substitute_type, substitute_function_body, inject_builtin_enums};

use rustc_hash::FxHashMap;

use crate::ir::types::*;
use crate::parser::ast::{self, Expr, GenericParam, Item, Stmt, Type};
use crate::span::{Span, Spanned};

use super::types::{mangle_generic_name, mangle_type_for_name, op_mangle_suffix, TypeMapper};

/// The kind of generic template being instantiated.
#[derive(Debug, Clone, Copy)]
pub enum TemplateKind {
    Struct,
    Enum,
    Function,
}

/// A per-call-site instantiation of a method-level-generic equip method.
/// Generated by `discover_method_instances` from typecheck's `expr_types`
/// side table. Each entry specialises an equip method like
/// `equip [T] VectorIter[T]: U map[U, F](F f)` into a free-function-shaped
/// symbol with merged substitutions for both T (from the receiver) and
/// U / F (from the call-site generic args).
#[derive(Debug, Clone)]
pub struct MethodInstance {
    /// Base name of the equipped type, e.g. "VectorIter".
    pub equip_base: String,
    /// Concrete type arguments for the equipped type, e.g. `[int]`.
    pub equip_type_args: Vec<Spanned<Type>>,
    /// Mangled name of the concrete equipped type, e.g. "VectorIter__int64_t".
    pub mangled_type: String,
    /// Method name as it appears in source, e.g. "map".
    pub method_name: String,
    /// Method-level generic arguments from the call site, e.g. `[int, int(int)]`.
    pub method_type_args: Vec<Spanned<Type>>,
    /// Fully mangled target symbol used by codegen, e.g.
    /// `VectorIter__int64_t__map__int64_t__GorgetClosure`.
    pub mangled_symbol: String,
}

/// Collects generic templates and discovered instantiations, then monomorphizes them.
pub struct GenericCollector {
    /// Generic struct templates: base_name → AST StructDef.
    struct_templates: FxHashMap<String, ast::StructDef>,
    /// Generic enum templates: base_name → AST EnumDef.
    enum_templates: FxHashMap<String, ast::EnumDef>,
    /// Non-generic enum definitions: enum_name → AST EnumDef.
    /// Used for AST-level expansion of `variant_payloads(T)` inside `meta for` match arms.
    non_generic_enum_defs: FxHashMap<String, ast::EnumDef>,
    /// Generic function templates: base_name → AST FunctionDef.
    fn_templates: FxHashMap<String, ast::FunctionDef>,
    /// Generic equip templates: base_type_name → Vec<EquipBlock>.
    equip_templates: FxHashMap<String, Vec<ast::EquipBlock>>,
    /// Discovered instantiations: (base_name, concrete_type_args) → mangled_name.
    /// Uses stringified type args as key for deduplication.
    instances: Vec<(String, Vec<Spanned<Type>>, String, TemplateKind)>,
    /// Already-registered mangled names (for dedup).
    registered: FxHashMap<String, ()>,
    /// When scanning inside a generic function/equip body, the set of type parameter
    /// names (e.g., {"T", "U"}). Calls using these as type args are deferred until
    /// transitive discovery resolves them to concrete types.
    current_generic_params: Option<Vec<String>>,
    /// Meta op bindings for each mangled function name: mangled → [(param_name, BinaryOp)].
    /// Populated during scan when MetaOpToken args are detected.
    meta_op_bindings: FxHashMap<String, Vec<(String, ast::BinaryOp)>>,
    /// Per-call-site instantiations of method-level-generic equip methods.
    /// Populated by `discover_method_instances`; consumed by sig + body lowering.
    method_instances: Vec<MethodInstance>,
    /// Dedup set keyed by the fully mangled symbol.
    method_instances_registered: FxHashMap<String, ()>,
    /// Trait definitions by name. Populated from `Item::Trait` during
    /// `collect_templates`. Used to find default-method bodies when an
    /// equip block doesn't explicitly override them — the per-call-site
    /// mono path looks here for method-level-generic defaults like
    /// `bool any[F](&self, F pred)` declared on `trait Iterator[T]:`.
    trait_defs: FxHashMap<String, ast::TraitDef>,
}

impl GenericCollector {
    pub fn new() -> Self {
        Self {
            struct_templates: FxHashMap::default(),
            enum_templates: FxHashMap::default(),
            non_generic_enum_defs: FxHashMap::default(),
            fn_templates: FxHashMap::default(),
            equip_templates: FxHashMap::default(),
            instances: Vec::new(),
            registered: FxHashMap::default(),
            current_generic_params: None,
            meta_op_bindings: FxHashMap::default(),
            method_instances: Vec::new(),
            method_instances_registered: FxHashMap::default(),
            trait_defs: FxHashMap::default(),
        }
    }

    /// Return the set of GIR-lowered generic equip method names.
    /// These are methods with Block/Expression bodies (not Extern/Declaration).
    pub fn gir_equip_method_names(&self) -> Vec<String> {
        use crate::parser::ast::FunctionBody;
        let mut names = Vec::new();
        for (base_name, _type_args, mangled_type_name, kind) in &self.instances {
            if !matches!(kind, TemplateKind::Struct | TemplateKind::Enum) { continue; }
            if let Some(equip_blocks) = self.equip_templates.get(base_name) {
                for equip in equip_blocks {
                    for method in &equip.items {
                        if !matches!(method.node.body, FunctionBody::Extern(_) | FunctionBody::Declaration) {
                            names.push(format!("{mangled_type_name}__{}", method.node.name.node));
                        }
                    }
                }
            }
        }
        names
    }

    /// Phase 1: Collect all generic templates from the AST module.
    pub fn collect_templates(&mut self, ast_module: &ast::Module) {
        // First pass: collect trait definitions so equip blocks below can
        // consult them (e.g. to check if the trait has method-generic
        // defaults). Iteration order in the module is source-dependent; the
        // fixture might define the equip BEFORE the auto-loaded std.iter
        // appends its traits.
        fn collect_traits_first(items: &[Spanned<Item>], out: &mut FxHashMap<String, ast::TraitDef>) {
            for item in items {
                match &item.node {
                    Item::Trait(td) => {
                        out.insert(td.name.node.clone(), td.clone());
                    }
                    Item::Module { items: inner, .. } => collect_traits_first(inner, out),
                    _ => {}
                }
            }
        }
        collect_traits_first(&ast_module.items, &mut self.trait_defs);

        for item in &ast_module.items {
            match &item.node {
                Item::Struct(s) if s.generic_params.is_some() => {
                    self.struct_templates.insert(s.name.node.clone(), s.clone());
                }
                Item::Enum(e) if e.generic_params.is_some() => {
                    self.enum_templates.insert(e.name.node.clone(), e.clone());
                }
                Item::Enum(e) if e.generic_params.is_none() => {
                    // Store non-generic enums for AST-level variant_payloads expansion
                    // during MetaFor match arm scanning.
                    self.non_generic_enum_defs.insert(e.name.node.clone(), e.clone());
                }
                Item::Function(f) if f.generic_params.is_some() => {
                    self.fn_templates.insert(f.name.node.clone(), f.clone());
                }
                Item::ExternBlock(ext) => {
                    // Generic extern fns declared inside `extern "C":` / `extern "Gorget":`
                    // blocks must be registered as templates so callers with type args
                    // (`f[int, int](...)`) trigger monomorphization and the post-pass in
                    // `ir/lowering/mod.rs` can propagate the C symbol binding. Inline
                    // extern decls (`extern int f[K, V](...) = "sym"`) already flow
                    // through the Item::Function branch above.
                    for func_spanned in &ext.items {
                        let f = &func_spanned.node;
                        if f.generic_params.is_some() {
                            self.fn_templates.insert(f.name.node.clone(), f.clone());
                        }
                    }
                }
                Item::Trait(_) => {
                    // Already collected in the first pass above.
                }
                Item::Equip(equip) => {
                    if let Type::Named { name, generic_args } = &equip.type_.node {
                        let has_generic_equip = !generic_args.is_empty() || equip.generic_params.is_some();
                        let has_method_level_generic = equip.items.iter()
                            .any(|m| m.node.generic_params.is_some());
                        // Also register non-generic equips whose trait
                        // has defaults OR is one of the iterator-
                        // protocol traits (`Iterable`/`Iterator`/
                        // `IntoIterable`). Chain inference via
                        // `infer_expr_ast_type` walks receivers through
                        // `equip_templates`; `equip Counter with
                        // Iterable[int]` needs to be reachable so
                        // `Counter(0, 5).iter()` resolves to CounterIter,
                        // even when Iterable's trait_def isn't in the
                        // module (prelude placeholder). Restricting to
                        // iterator-protocol names avoids dragging in
                        // unrelated trait equips (RWLock / Channel /
                        // etc.) that were working through their own
                        // dispatch paths and regress on universal
                        // registration.
                        let trait_name = equip.trait_.as_ref().and_then(|t| match &t.trait_name.node {
                            Type::Named { name, .. } => Some(name.node.as_str()),
                            _ => None,
                        });
                        let trait_has_default = trait_name
                            .and_then(|tn| {
                                self.trait_defs.get(tn).map(|td| {
                                    td.items.iter().any(|it| {
                                        matches!(&it.node, ast::TraitItem::Method(m)
                                            if matches!(m.body,
                                                ast::FunctionBody::Block(_)
                                                | ast::FunctionBody::Expression(_)))
                                    })
                                })
                            })
                            .unwrap_or(false);
                        let is_iter_protocol = matches!(trait_name,
                            Some("Iterator" | "Iterable" | "IntoIterable"));
                        if has_generic_equip || has_method_level_generic || trait_has_default || is_iter_protocol {
                            self.equip_templates
                                .entry(name.node.clone())
                                .or_default()
                                .push(equip.clone());
                        }
                    }
                }
                _ => {}
            }
        }

        // Inject built-in Option[T] and Result[T, E] if not already present
        inject_builtin_enums(&mut self.enum_templates);
    }

    /// Phase 2: Walk the AST to discover all concrete generic usages.
    pub fn discover_usages(&mut self, ast_module: &ast::Module) {
        for item in &ast_module.items {
            match &item.node {
                Item::Function(f) => {
                    self.scan_function(f);
                }
                Item::Struct(s) if s.generic_params.is_none() => {
                    // Non-generic struct fields may reference generic types
                    for field in &s.fields {
                        self.scan_type(&field.node.type_);
                    }
                }
                Item::Enum(e) if e.generic_params.is_none() => {
                    for variant in &e.variants {
                        match &variant.node.fields {
                            ast::VariantFields::Tuple(types) => {
                                for ty in types {
                                    self.scan_type(ty);
                                }
                            }
                            ast::VariantFields::Unit => {}
                        }
                    }
                }
                Item::Equip(equip) if equip.generic_params.is_none() => {
                    // The equip's target may carry *target-implicit* generic
                    // params, e.g. `equip Tensor[T]:` where `[T]` comes from
                    // the struct decl rather than an explicit `equip [T]`
                    // prefix. Those names must be treated as unresolved while
                    // scanning the method bodies, otherwise a method like
                    // `Tensor[T] reshape(self, ...)` registers the phantom
                    // concrete instance `Tensor__T` (its drop then references
                    // the never-defined `Shared__Vector__T__drop`).
                    let equip_params: Vec<String> = match &equip.type_.node {
                        Type::Named { generic_args, .. } => generic_args
                            .iter()
                            .filter_map(|a| match &a.node {
                                Type::Named { name, generic_args }
                                    if generic_args.is_empty() =>
                                {
                                    Some(name.node.clone())
                                }
                                _ => None,
                            })
                            .collect(),
                        _ => Vec::new(),
                    };
                    let prev = self.current_generic_params.take();
                    if !equip_params.is_empty() {
                        self.current_generic_params = Some(equip_params);
                    }
                    for method in &equip.items {
                        self.scan_function(&method.node);
                    }
                    self.current_generic_params = prev;
                }
                _ => {}
            }
        }
    }

    /// Check if a type references any of the current generic params.
    fn type_has_generic_param(&self, ty: &Type) -> bool {
        if let Some(ref params) = self.current_generic_params {
            match ty {
                Type::Named { name, generic_args } if generic_args.is_empty() => {
                    params.iter().any(|p| p == &name.node)
                }
                Type::Named { generic_args, .. } => {
                    generic_args.iter().any(|a| self.type_has_generic_param(&a.node))
                }
                _ => false,
            }
        } else {
            false
        }
    }

    /// Check if any type in a list of type args contains an unresolved generic param.
    fn has_unresolved_type_args(&self, type_args: &[Spanned<Type>]) -> bool {
        type_args.iter().any(|a| self.type_has_generic_param(&a.node))
    }

    /// Register a concrete generic instantiation.
    fn register_instance(
        &mut self,
        base_name: &str,
        type_args: &[Spanned<Type>],
        kind: TemplateKind,
    ) -> String {
        let mangled = mangle_generic_name(base_name, type_args);
        if self.registered.contains_key(&mangled) {
            return mangled;
        }
        self.registered.insert(mangled.clone(), ());
        self.instances
            .push((base_name.to_string(), type_args.to_vec(), mangled.clone(), kind));
        mangled
    }

    /// Register a concrete generic function instantiation that has `meta op` bindings.
    /// The mangled name gets an additional `__<op_suffix>` per op binding.
    fn register_instance_with_ops(
        &mut self,
        base_name: &str,
        type_args: &[Spanned<Type>],
        op_bindings: Vec<(String, ast::BinaryOp)>,
    ) -> String {
        // Base mangled name from type args
        let mut mangled = mangle_generic_name(base_name, type_args);
        // Append one suffix per op binding
        for (_, op) in &op_bindings {
            mangled.push_str("__");
            mangled.push_str(op_mangle_suffix(*op));
        }
        if !self.registered.contains_key(&mangled) {
            self.registered.insert(mangled.clone(), ());
            self.instances.push((
                base_name.to_string(),
                type_args.to_vec(),
                mangled.clone(),
                TemplateKind::Function,
            ));
        }
        // Always store/update the bindings (idempotent for same mangled name)
        self.meta_op_bindings.entry(mangled.clone()).or_insert(op_bindings);
        mangled
    }

    /// Return the meta op bindings for a mangled function name (empty slice if none).
    pub fn meta_op_bindings_for(&self, mangled: &str) -> &[(String, ast::BinaryOp)] {
        self.meta_op_bindings
            .get(mangled)
            .map(|v| v.as_slice())
            .unwrap_or(&[])
    }

    /// Scan a function definition for generic usages.
    fn scan_function(&mut self, func: &ast::FunctionDef) {
        // Track generic params so we can skip unresolved type-arg usages.
        // Preserve any params set by the caller (e.g. an equip block's
        // target-implicit `[T]`, see `discover_usages`) and MERGE the
        // function's own generic params on top — a method like
        // `Tensor[T] reshape(self, ...)` inside `equip Tensor[T]:` must
        // still see `T` as unresolved so it isn't registered as the phantom
        // concrete instance `Tensor__T`.
        let prev = self.current_generic_params.take();
        let mut names: Vec<String> = prev.clone().unwrap_or_default();
        if let Some(ref gp) = func.generic_params {
            names.extend(gp.node.params.iter().map(|p| match &p.node {
                GenericParam::Type { name, .. } => name.node.clone(),
                GenericParam::Const { name: s, .. } => s.node.clone(),
            }));
        }
        if !names.is_empty() {
            self.current_generic_params = Some(names);
        }

        // Return type
        self.scan_type(&func.return_type);
        // Params
        for p in &func.params {
            self.scan_type(&p.node.type_);
        }
        // Body
        match &func.body {
            ast::FunctionBody::Block(block) => self.scan_block(block),
            ast::FunctionBody::Expression(expr) => self.scan_expr(expr),
            _ => {}
        }

        self.current_generic_params = prev;
    }

    /// Scan an AST type for generic instantiations.
    fn scan_type(&mut self, ty: &Spanned<Type>) {
        match &ty.node {
            Type::Named { name, generic_args } if !generic_args.is_empty() => {
                // Skip if any type arg contains an unresolved generic param
                if self.has_unresolved_type_args(generic_args) {
                    return;
                }
                // Recursively scan the type args themselves
                for arg in generic_args {
                    self.scan_type(arg);
                }
                // Register the instantiation
                let base = &name.node;
                if self.struct_templates.contains_key(base) {
                    self.register_instance(base, generic_args, TemplateKind::Struct);
                } else if self.enum_templates.contains_key(base) {
                    self.register_instance(base, generic_args, TemplateKind::Enum);
                } else if matches!(base.as_str(), "Vector" | "Deque" | "Dict" | "HashMap" | "Set" | "HashSet" | "Box") {
                    // Runtime collection types — register as Struct so the type name is
                    // available for method call mangling (no struct template to monomorphize)
                    self.register_instance(base, generic_args, TemplateKind::Struct);
                } else if matches!(base.as_str(), "Option" | "Result") {
                    // Option/Result generic types — register as Enum so the type definition
                    // is emitted in C output (auto-registered by map_ast_type_mut)
                    self.register_instance(base, generic_args, TemplateKind::Enum);
                }
            }
            Type::Tuple(elems) => {
                for elem in elems {
                    self.scan_type(elem);
                }
            }
            Type::Function { return_type, params, .. } => {
                self.scan_type(return_type);
                for p in params {
                    self.scan_type(p);
                }
            }
            Type::Array { element, .. } | Type::Slice { element } => {
                self.scan_type(element);
            }
            Type::Ref(inner) | Type::Owned(inner) => {
                self.scan_type(inner);
            }
            _ => {}
        }
    }

    /// Scan a block for generic usages.
    fn scan_block(&mut self, block: &ast::Block) {
        for stmt in &block.stmts {
            self.scan_stmt(stmt);
        }
    }

    /// Scan a statement for generic usages.
    fn scan_stmt(&mut self, stmt: &Spanned<Stmt>) {
        match &stmt.node {
            Stmt::VarDecl { type_, value, .. } => {
                self.scan_type(type_);
                self.scan_expr(value);
            }
            Stmt::Assign { target, value } => {
                self.scan_expr(target);
                self.scan_expr(value);
            }
            Stmt::CompoundAssign { target, value, .. } => {
                self.scan_expr(target);
                self.scan_expr(value);
            }
            Stmt::Return(Some(expr)) | Stmt::Expr(expr) | Stmt::Throw(expr) => {
                self.scan_expr(expr);
            }
            Stmt::If { condition, then_body, elif_branches, else_body } => {
                self.scan_expr(condition);
                self.scan_block(then_body);
                for (cond, body) in elif_branches {
                    self.scan_expr(cond);
                    self.scan_block(body);
                }
                if let Some(else_body) = else_body {
                    self.scan_block(else_body);
                }
            }
            Stmt::While { condition, body, .. } => {
                self.scan_expr(condition);
                self.scan_block(body);
            }
            Stmt::For { iterable, body, .. } => {
                self.scan_expr(iterable);
                self.scan_block(body);
            }
            Stmt::Match { scrutinee, arms, else_arm } => {
                self.scan_expr(scrutinee);
                for item in arms {
                    match item {
                        ast::MatchItem::Arm(arm) => {
                            self.scan_expr(&arm.body);
                            if let Some(guard) = &arm.guard {
                                self.scan_expr(guard);
                            }
                        }
                        ast::MatchItem::MetaFor { vars, range, arm_template, .. } => {
                            // Expand variant_payloads at scan time so generic calls inside
                            // arm templates (e.g. col_slice_inner[T]) get monomorphized.
                            self.scan_meta_for_match_arm(vars, range, arm_template);
                        }
                    }
                }
                if let Some(else_body) = else_arm {
                    self.scan_block(else_body);
                }
            }
            Stmt::With { bindings, body } => {
                for binding in bindings {
                    self.scan_expr(&binding.expr);
                }
                self.scan_block(body);
            }
            Stmt::Loop { body } | Stmt::Unsafe { body } | Stmt::NamedScope { body, .. } => {
                self.scan_block(body);
            }
            Stmt::Assert { condition, message } | Stmt::AssertReturn { condition, message } => {
                self.scan_expr(condition);
                if let Some(msg) = message {
                    self.scan_expr(msg);
                }
            }
            Stmt::Snapshot { value, .. } => {
                self.scan_expr(value);
            }
            // Delayed meta stmts: scan all branches (conservative — we can't
            // evaluate typename(T) yet; all branches may reference generic calls).
            Stmt::MetaIf { condition, then_body, elif_branches, else_body, .. } => {
                self.scan_expr(condition);
                self.scan_block(then_body);
                for (cond, body) in elif_branches {
                    self.scan_expr(cond);
                    self.scan_block(body);
                }
                if let Some(eb) = else_body {
                    self.scan_block(eb);
                }
            }
            Stmt::MetaFor { range, body, .. } => {
                self.scan_expr(range);
                self.scan_block(body);
            }
            Stmt::MetaMatch { scrutinee, arms, else_arm, .. } => {
                self.scan_expr(scrutinee);
                for (case_expr, body) in arms {
                    self.scan_expr(case_expr);
                    self.scan_block(body);
                }
                if let Some(eb) = else_arm {
                    self.scan_block(eb);
                }
            }
            Stmt::MetaWhile { body, .. } => {
                self.scan_block(body);
            }
            Stmt::MetaConst { value, .. } => {
                self.scan_expr(value);
            }
            _ => {}
        }
    }

    /// Scan a `meta for vname, T in variant_payloads(EnumName):` match item.
    ///
    /// Expands the range by looking up the enum definition in the AST, then scans
    /// the arm template body once per variant with concrete variable substitutions.
    /// This ensures generic calls like `col_slice_inner[T]` are discovered for
    /// monomorphization even though the outer function is non-generic.
    fn scan_meta_for_match_arm(
        &mut self,
        vars: &[crate::span::Spanned<String>],
        range: &Spanned<Expr>,
        arm_template: &ast::MatchArm,
    ) {
        use crate::semantic::meta::{MetaValue, meta_str_to_type, substitute_match_arm};

        // Extract enum name from variant_payloads(EnumName) call
        let enum_name = match Self::extract_variant_payloads_enum_name(range) {
            Some(n) => n,
            None => {
                // Unknown range form — scan template conservatively with no substitution
                self.scan_expr(&arm_template.body);
                return;
            }
        };

        // Look up enum definition in the AST-level store
        let enum_def = match self.non_generic_enum_defs.get(&enum_name) {
            Some(e) => e.clone(),
            None => {
                self.scan_expr(&arm_template.body);
                return;
            }
        };

        // For each variant, build substitution env and scan the concrete arm body
        for variant in &enum_def.variants {
            let vname = variant.node.name.node.clone();

            // Extract inner type arg from the variant's first tuple field, if any
            let inner_type_str: String = match &variant.node.fields {
                ast::VariantFields::Tuple(types) if types.len() == 1 => {
                    // For a field like TypedColumn[int], take the first generic arg
                    match &types[0].node {
                        Type::Named { generic_args, .. } if !generic_args.is_empty() => {
                            crate::semantic::meta::type_to_canonical_name(&generic_args[0].node)
                        }
                        other => crate::semantic::meta::type_to_canonical_name(other),
                    }
                }
                _ => String::new(),
            };

            let mut env: rustc_hash::FxHashMap<String, MetaValue> =
                rustc_hash::FxHashMap::default();
            let mut type_env: rustc_hash::FxHashMap<String, crate::parser::ast::Type> =
                rustc_hash::FxHashMap::default();

            if !vars.is_empty() {
                env.insert(vars[0].node.clone(), MetaValue::Str(vname));
            }
            if vars.len() >= 2 && !inner_type_str.is_empty() {
                let key = vars[1].node.clone();
                env.insert(key.clone(), MetaValue::Str(inner_type_str.clone()));
                type_env.insert(key, meta_str_to_type(&inner_type_str));
            }

            let mut concrete_arm = arm_template.clone();
            substitute_match_arm(&mut concrete_arm, &env, &type_env);
            self.scan_expr(&concrete_arm.body);
        }
    }

    /// Extract the enum type name from a `variant_payloads(EnumName)` call expression.
    fn extract_variant_payloads_enum_name(range: &Spanned<Expr>) -> Option<String> {
        if let Expr::Call { callee, args, .. } = &range.node {
            if let Expr::Identifier(name) = &callee.node {
                if name == "variant_payloads" && !args.is_empty() {
                    if let Expr::Identifier(enum_name) = &args[0].node.value.node {
                        return Some(enum_name.clone());
                    }
                }
            }
        }
        None
    }

    /// Scan an expression for generic usages.
    fn scan_expr(&mut self, expr: &Spanned<Expr>) {
        match &expr.node {
            Expr::Call { callee, generic_args, args } => {
                self.scan_expr(callee);
                // Generic function/struct call: identity[int](42), TypedColumn[int](d, m)
                if let Some(type_args) = generic_args {
                    // Skip registering if any type arg is an unresolved generic param
                    // (will be discovered transitively when the outer function is instantiated)
                    if !self.has_unresolved_type_args(type_args) {
                        for arg in type_args {
                            self.scan_type(arg);
                        }
                        if let Expr::Identifier(name) = &callee.node {
                            if self.fn_templates.contains_key(name.as_str()) {
                                // Collect meta op bindings from MetaOpToken args
                                let template = self.fn_templates.get(name.as_str()).expect("BUG: generic template not found for monomorphization");
                                let op_bindings: Vec<(String, ast::BinaryOp)> = template
                                    .params
                                    .iter()
                                    .zip(args.iter())
                                    .filter_map(|(param, arg)| {
                                        if param.node.is_meta_op {
                                            if let Expr::MetaOpToken(op) = &arg.node.value.node {
                                                return Some((param.node.name.node.clone(), *op));
                                            }
                                        }
                                        None
                                    })
                                    .collect();
                                if op_bindings.is_empty() {
                                    self.register_instance(name, type_args, TemplateKind::Function);
                                } else {
                                    self.register_instance_with_ops(name, type_args, op_bindings);
                                }
                            } else if self.struct_templates.contains_key(name.as_str()) {
                                // Struct constructor call with generic args: TypedColumn[int](...)
                                self.register_instance(name, type_args, TemplateKind::Struct);
                            }
                        }
                    }
                }
                for arg in args {
                    self.scan_expr(&arg.node.value);
                }
            }
            Expr::MethodCall { receiver, generic_args, args, .. } => {
                self.scan_expr(receiver);
                if let Some(type_args) = generic_args {
                    for arg in type_args {
                        self.scan_type(arg);
                    }
                }
                for arg in args {
                    self.scan_expr(&arg.node.value);
                }
            }
            Expr::StructLiteral { generic_args, args, name, .. } => {
                if let Some(type_args) = generic_args {
                    if !self.has_unresolved_type_args(type_args) {
                        for arg in type_args {
                            self.scan_type(arg);
                        }
                        if self.struct_templates.contains_key(name.node.as_str()) {
                            self.register_instance(&name.node, type_args, TemplateKind::Struct);
                        } else if self.enum_templates.contains_key(name.node.as_str()) {
                            self.register_instance(&name.node, type_args, TemplateKind::Enum);
                        }
                    }
                }
                for arg in args {
                    self.scan_expr(arg);
                }
            }
            Expr::BinaryOp { left, right, .. } => {
                self.scan_expr(left);
                self.scan_expr(right);
            }
            Expr::UnaryOp { operand, .. } => {
                self.scan_expr(operand);
            }
            Expr::FieldAccess { object, .. } => {
                self.scan_expr(object);
            }
            Expr::Index { object, index } => {
                self.scan_expr(object);
                self.scan_expr(index);
            }
            Expr::If { condition, then_branch, elif_branches, else_branch } => {
                self.scan_expr(condition);
                self.scan_expr(then_branch);
                for (cond, body) in elif_branches {
                    self.scan_expr(cond);
                    self.scan_expr(body);
                }
                if let Some(eb) = else_branch {
                    self.scan_expr(eb);
                }
            }
            Expr::Move { expr: inner }
            | Expr::Propagate { expr: inner }
            | Expr::MutableBorrow { expr: inner } => {
                self.scan_expr(inner);
            }
            // Error-handling wrappers: the inner call (and the recovery /
            // transform arm) can instantiate generics. PRE-EXISTING gap made
            // load-bearing by D29: `write_str[File](&f, s)! catch (e): 0`
            // (a marked lib-generic call under `catch`) lost its instance —
            // undefined symbol at link. Same class for `rethrow`/fault-catch.
            Expr::Catch { expr: inner, recovery, .. } => {
                self.scan_expr(inner);
                self.scan_expr(recovery);
            }
            Expr::Rethrow { expr: inner, transform, .. } => {
                self.scan_expr(inner);
                self.scan_expr(transform);
            }
            Expr::FaultCatch { expr: inner, handler, .. } => {
                self.scan_expr(inner);
                self.scan_expr(handler);
            }
            Expr::Range { start, end, .. } => {
                if let Some(s) = start { self.scan_expr(s); }
                if let Some(e) = end { self.scan_expr(e); }
            }
            Expr::Closure { body, .. } | Expr::ImplicitClosure { body } => {
                self.scan_expr(body);
            }
            Expr::TupleLiteral(elems) | Expr::ArrayLiteral(elems) => {
                for e in elems {
                    self.scan_expr(e);
                }
            }
            Expr::StringLiteral(_, interp_exprs) => {
                // Scan pre-parsed interpolation expressions for generic usages
                // (e.g., `f"{add_values[int](3, 4)}"`). The parser populates
                // `interp_exprs` for every f-string; falling back to re-parsing
                // would skip the typecheck rewriter and inferred targs.
                for ie in interp_exprs {
                    self.scan_expr(ie);
                }
            }
            // Block expressions: multi-statement match arm bodies, do-blocks, etc.
            Expr::Block(block) | Expr::Do { body: block } => {
                self.scan_block(block);
            }
            // Expression-level match (arm bodies may contain VarDecls with generic types)
            Expr::Match { scrutinee, arms, else_arm } => {
                self.scan_expr(scrutinee);
                for arm in arms {
                    self.scan_expr(&arm.body);
                }
                if let Some(eb) = else_arm {
                    self.scan_expr(eb);
                }
            }
            Expr::MetaOpInfix { left, right, .. } => {
                self.scan_expr(left);
                self.scan_expr(right);
            }
            // MetaOpToken is a leaf — no sub-expressions to scan.
            Expr::MetaOpToken(_) => {}
            _ => {}
        }
    }

    /// Phase 2b: Transitively discover generic usages inside monomorphized function bodies.
    /// When `tensor_neg[int]` calls `tensor_zeros[T]`, the initial scan skips it (T is abstract).
    /// This phase substitutes T→int in the template body and re-scans to discover `tensor_zeros[int]`.
    ///
    /// Also walks **equip method bodies** for each monomorphized struct/enum instance:
    /// when `Vector[int]` is instantiated, its `iter()` method body is scanned with T→int
    /// substitution so that nested struct constructions like `VectorIter[T](self, 0)` get
    /// registered as `VectorIter[int]`. Without this, generic equip methods that construct
    /// other generic types silently skip the dependent type's monomorphization and the
    /// GIR validator later panics on "reference to undefined type".
    pub fn discover_transitive(&mut self, _ast_module: Option<&ast::Module>) {
        let mut i = 0;
        while i < self.instances.len() {
            let (base_name, type_args, _, kind) = self.instances[i].clone();
            i += 1;
            match kind {
                TemplateKind::Function => {
                    let template = match self.fn_templates.get(&base_name) {
                        Some(t) => t.clone(),
                        None => continue,
                    };
                    let subs = build_type_substitutions(template.generic_params.as_ref(), &type_args);
                    if subs.is_empty() {
                        continue;
                    }
                    // Substitute types in the template body and re-scan (with no generic params context,
                    // so all discovered usages are concrete).
                    let prev = self.current_generic_params.take();
                    let substituted = substitute_function_body(&template, &subs);
                    self.scan_function(&substituted);
                    // Also re-walk for method-call discovery so nested method-
                    // generic calls register their instances. Without this, a
                    // body like `apply[Hashable T, Hasher H](T v, H &h):
                    // v.hash[H](&h)` discovers `v.hash[H]` against the
                    // abstract T (no equip template), comes up empty, and the
                    // call site falls through to the trait vtable forwarder
                    // which has an empty body for method-generic methods. The
                    // post-substitution rescan with concrete T=Point catches
                    // `v.hash[MyHasher]` against the Point equip block.
                    let mut env = LocalTypeEnv::default();
                    populate_env_from_params(&mut env, &substituted.params);
                    self.walk_fn_body_for_method_calls(&substituted.body, &mut env);
                    self.current_generic_params = prev;
                }
                TemplateKind::Struct | TemplateKind::Enum => {
                    // Clone the equip blocks so we can walk them while self.instances grows.
                    let equip_blocks = match self.equip_templates.get(&base_name) {
                        Some(blocks) => blocks.clone(),
                        None => continue,
                    };
                    for equip in &equip_blocks {
                        let subs = build_equip_type_substitutions(equip, &type_args);
                        if subs.is_empty() {
                            continue;
                        }
                        for method in &equip.items {
                            let prev = self.current_generic_params.take();
                            // `substitute_function_body` preserves any
                            // method-level generic params that the equip-level
                            // substitution didn't cover (e.g. `[U, F]` on
                            // `map[U, F]`). `scan_function` below picks them
                            // up as the unresolved-params context, so types
                            // like `MapIter[int, U, F]` are skipped rather
                            // than registered as phantom concrete structs.
                            let substituted = substitute_function_body(&method.node, &subs);
                            self.scan_function(&substituted);
                            self.current_generic_params = prev;
                        }
                        // NOTE: Trait default-method bodies deliberately
                        // NOT scanned here. An earlier revision added a
                        // scanner with `Self → substituted equipped type`
                        // so defaults like `TakeIter[Self, T] take(self,
                        // int n): return TakeIter[Self, T](self, n)` would
                        // register `TakeIter[VectorIter[int], int]` when
                        // processing the VectorIter[int] instance. That
                        // produced an infinite loop: each new instance
                        // (TakeIter[VectorIter[int], int]) is itself an
                        // Iterator[T] impl, so the next pass through the
                        // while-loop would scan ITS `take` default and
                        // register `TakeIter[TakeIter[..], int]`, ad
                        // infinitum. Correct handling wants to register
                        // only the instances actually hit by user-code
                        // call sites (via `discover_method_instances` or
                        // typecheck's expr_types) — not speculatively
                        // expand every Iterator implementor's full
                        // adapter surface. Tracked as Phase 2c follow-up.
                    }
                }
            }
        }
    }

    /// Phase 2.5: Discover per-call-site instantiations of method-level-generic
    /// equip methods.
    ///
    /// Walks every `Expr::MethodCall` in the module. When the call carries
    /// explicit generic args AND the receiver's inferred type (from
    /// `expr_types`) resolves to a generic struct whose equip block defines
    /// a method of that name with method-level generic params, register a
    /// `MethodInstance` capturing the merged substitution.
    ///
    /// Independent of typecheck's `method_resolutions` side table: we do the
    /// lookup ourselves against our own `equip_templates`, which makes this
    /// robust to the fallback paths in typecheck that don't populate
    /// `method_resolutions` (cross-module, generic-receiver dispatch).
    ///
    /// Transitive discovery through substituted bodies is deliberately not
    /// wired here — once a caller specialises a generic function, its body
    /// is re-scanned with concrete types via `discover_transitive`, but that
    /// rescan produces dummy spans that `expr_types` can't key. Method-level
    /// generic dispatch inside generic function bodies is still handled by
    /// the existing `scan_expr` MethodCall arm (which defers registration
    /// until the outer fn specialises) — the new code path layers on top.
    pub fn discover_method_instances(
        &mut self,
        ast_module: &ast::Module,
        _analysis: &crate::semantic::AnalysisResult,
    ) {
        for item in &ast_module.items {
            match &item.node {
                Item::Function(f) => {
                    let mut env = LocalTypeEnv::default();
                    populate_env_from_params(&mut env, &f.params);
                    self.walk_fn_body_for_method_calls(&f.body, &mut env);
                }
                Item::Equip(equip) => {
                    for method in &equip.items {
                        let mut env = LocalTypeEnv::default();
                        // `self` binds to the equipped type (used only as a starting
                        // point for `self.field` chains, which we don't track deeply).
                        populate_env_from_params(&mut env, &method.node.params);
                        self.walk_fn_body_for_method_calls(&method.node.body, &mut env);
                    }
                }
                Item::Module { items, .. } => {
                    self.walk_module_items_for_method_calls(items);
                }
                _ => {}
            }
        }
    }

    fn walk_module_items_for_method_calls(&mut self, items: &[Spanned<Item>]) {
        for item in items {
            match &item.node {
                Item::Function(f) => {
                    let mut env = LocalTypeEnv::default();
                    populate_env_from_params(&mut env, &f.params);
                    self.walk_fn_body_for_method_calls(&f.body, &mut env);
                }
                Item::Equip(equip) => {
                    for method in &equip.items {
                        let mut env = LocalTypeEnv::default();
                        populate_env_from_params(&mut env, &method.node.params);
                        self.walk_fn_body_for_method_calls(&method.node.body, &mut env);
                    }
                }
                Item::Module { items: inner, .. } => {
                    self.walk_module_items_for_method_calls(inner);
                }
                _ => {}
            }
        }
    }

    fn walk_fn_body_for_method_calls(&mut self, body: &ast::FunctionBody, env: &mut LocalTypeEnv) {
        match body {
            ast::FunctionBody::Block(block) => self.walk_block_for_method_calls(block, env),
            ast::FunctionBody::Expression(expr) => self.walk_expr_for_method_calls(expr, env),
            _ => {}
        }
    }

    fn walk_block_for_method_calls(&mut self, block: &ast::Block, env: &mut LocalTypeEnv) {
        // Shadow with a local scope so let bindings don't leak to siblings.
        let snapshot = env.snapshot();
        for stmt in &block.stmts {
            self.walk_stmt_for_method_calls(stmt, env);
        }
        env.restore(snapshot);
    }

    fn walk_stmt_for_method_calls(&mut self, stmt: &Spanned<Stmt>, env: &mut LocalTypeEnv) {
        match &stmt.node {
            Stmt::VarDecl { pattern, type_, value, .. } => {
                self.walk_expr_for_method_calls(value, env);
                if let Some(name) = pattern_binding_name(pattern) {
                    env.bind(name, type_.node.clone());
                }
            }
            Stmt::Assign { target, value } | Stmt::CompoundAssign { target, value, .. } => {
                self.walk_expr_for_method_calls(target, env);
                self.walk_expr_for_method_calls(value, env);
            }
            Stmt::Return(Some(expr)) | Stmt::Expr(expr) | Stmt::Throw(expr) => {
                self.walk_expr_for_method_calls(expr, env);
            }
            Stmt::If { condition, then_body, elif_branches, else_body } => {
                self.walk_expr_for_method_calls(condition, env);
                self.walk_block_for_method_calls(then_body, env);
                for (c, b) in elif_branches {
                    self.walk_expr_for_method_calls(c, env);
                    self.walk_block_for_method_calls(b, env);
                }
                if let Some(b) = else_body {
                    self.walk_block_for_method_calls(b, env);
                }
            }
            Stmt::While { condition, body, .. } => {
                self.walk_expr_for_method_calls(condition, env);
                self.walk_block_for_method_calls(body, env);
            }
            Stmt::For { pattern, iterable, body, .. } => {
                self.walk_expr_for_method_calls(iterable, env);
                // Narrow: if iterable is Vector[T]/VectorIter[T]/etc., bind the
                // loop var to T so method calls on the element resolve. This
                // is a best-effort — if we can't infer we just skip.
                let snapshot = env.snapshot();
                if let Some(iter_ty) = self.infer_expr_ast_type(iterable, env) {
                    if let Some(elem) = extract_iterator_element(&iter_ty) {
                        if let Some(name) = pattern_binding_name(pattern) {
                            env.bind(name, elem);
                        }
                    }
                }
                self.walk_block_for_method_calls(body, env);
                env.restore(snapshot);
            }
            Stmt::Match { scrutinee, arms, else_arm } => {
                self.walk_expr_for_method_calls(scrutinee, env);
                for item in arms {
                    if let ast::MatchItem::Arm(arm) = item {
                        self.walk_expr_for_method_calls(&arm.body, env);
                        if let Some(g) = &arm.guard {
                            self.walk_expr_for_method_calls(g, env);
                        }
                    }
                }
                if let Some(b) = else_arm {
                    self.walk_block_for_method_calls(b, env);
                }
            }
            Stmt::With { bindings, body } => {
                for binding in bindings {
                    self.walk_expr_for_method_calls(&binding.expr, env);
                }
                self.walk_block_for_method_calls(body, env);
            }
            Stmt::Loop { body } | Stmt::Unsafe { body } | Stmt::NamedScope { body, .. } => {
                self.walk_block_for_method_calls(body, env);
            }
            _ => {}
        }
    }

    fn walk_expr_for_method_calls(&mut self, expr: &Spanned<Expr>, env: &mut LocalTypeEnv) {
        match &expr.node {
            Expr::MethodCall { receiver, method, generic_args, args } => {
                self.walk_expr_for_method_calls(receiver, env);
                for arg in args {
                    self.walk_expr_for_method_calls(&arg.node.value, env);
                }
                if let Some(method_targs) = generic_args {
                    self.try_register_method_instance(receiver, method, method_targs, env);
                } else {
                    // Non-method-generic call. If the method resolves to a
                    // trait default whose return type mentions `Self` or the
                    // trait's own generics, register the monomorphised
                    // return-type struct so its constructor + inherent
                    // methods lower (e.g. `v.iter().take(3)` registers
                    // `TakeIter[VectorIter[int], int]` ahead of its `next()`
                    // call). Only covers DIRECT return-type registration —
                    // the registered instance's own trait defaults are left
                    // dormant to avoid the `TakeIter[TakeIter[..], ..]`
                    // infinite cascade.
                    self.try_register_default_return_type(receiver, method, env);
                }
            }
            Expr::Call { callee, args, .. } => {
                self.walk_expr_for_method_calls(callee, env);
                for arg in args {
                    self.walk_expr_for_method_calls(&arg.node.value, env);
                }
            }
            Expr::StructLiteral { args, .. } => {
                for arg in args {
                    self.walk_expr_for_method_calls(arg, env);
                }
            }
            Expr::BinaryOp { left, right, .. } => {
                self.walk_expr_for_method_calls(left, env);
                self.walk_expr_for_method_calls(right, env);
            }
            Expr::UnaryOp { operand, .. } => {
                self.walk_expr_for_method_calls(operand, env);
            }
            Expr::FieldAccess { object, .. } | Expr::TupleFieldAccess { object, .. } => {
                self.walk_expr_for_method_calls(object, env);
            }
            Expr::Index { object, index } => {
                self.walk_expr_for_method_calls(object, env);
                self.walk_expr_for_method_calls(index, env);
            }
            Expr::If { condition, then_branch, elif_branches, else_branch } => {
                self.walk_expr_for_method_calls(condition, env);
                self.walk_expr_for_method_calls(then_branch, env);
                for (cond, body) in elif_branches {
                    self.walk_expr_for_method_calls(cond, env);
                    self.walk_expr_for_method_calls(body, env);
                }
                if let Some(eb) = else_branch {
                    self.walk_expr_for_method_calls(eb, env);
                }
            }
            Expr::Range { start, end, .. } => {
                if let Some(s) = start { self.walk_expr_for_method_calls(s, env); }
                if let Some(e) = end { self.walk_expr_for_method_calls(e, env); }
            }
            Expr::Move { expr: inner }
            | Expr::Propagate { expr: inner }
            | Expr::MutableBorrow { expr: inner }
            | Expr::OptionalChain { object: inner, .. } => {
                self.walk_expr_for_method_calls(inner, env);
            }
            // Error-handling wrappers (see scan_expr — the same discovery class).
            Expr::Catch { expr: inner, recovery, .. } => {
                self.walk_expr_for_method_calls(inner, env);
                self.walk_expr_for_method_calls(recovery, env);
            }
            Expr::Rethrow { expr: inner, transform, .. } => {
                self.walk_expr_for_method_calls(inner, env);
                self.walk_expr_for_method_calls(transform, env);
            }
            Expr::FaultCatch { expr: inner, handler, .. } => {
                self.walk_expr_for_method_calls(inner, env);
                self.walk_expr_for_method_calls(handler, env);
            }
            Expr::DefaultOp { lhs, rhs } => {
                self.walk_expr_for_method_calls(lhs, env);
                self.walk_expr_for_method_calls(rhs, env);
            }
            Expr::Closure { body, .. } | Expr::ImplicitClosure { body } => {
                self.walk_expr_for_method_calls(body, env);
            }
            Expr::TupleLiteral(elems) | Expr::ArrayLiteral(elems) => {
                for e in elems {
                    self.walk_expr_for_method_calls(e, env);
                }
            }
            Expr::Block(block) => {
                self.walk_block_for_method_calls(block, env);
            }
            Expr::StringLiteral(_, interp_exprs) => {
                // Recurse into pre-parsed f-string interpolation expressions so
                // method calls inside `f"{...}"` participate in monomorphisation
                // discovery (per-call-site instance registration via
                // `try_register_method_instance`). Without this, mangled symbols
                // referenced from f-strings have no body emitted and link-fail.
                for ie in interp_exprs {
                    self.walk_expr_for_method_calls(ie, env);
                }
            }
            _ => {}
        }
    }

    fn try_register_method_instance(
        &mut self,
        receiver: &Spanned<Expr>,
        method_name: &Spanned<String>,
        method_targs: &[Spanned<Type>],
        env: &LocalTypeEnv,
    ) {
        // Any unresolved (generic-param) type arg? Defer — transitive discovery
        // will reach us once the outer function specialises.
        if self.has_unresolved_type_args(method_targs) {
            return;
        }
        // Resolve the receiver's concrete AST type via the local env. Typecheck's
        // `expr_types` only records generic-template return types for method
        // chains like `v.iter()` (the sig says `VectorIter[T]`, T stays abstract),
        // so we do our own walking-scope inference here using the template
        // shapes stored on the collector.
        let recv_ast = match self.infer_expr_ast_type(receiver, env) {
            Some(t) => t,
            None => return,
        };
        let (equip_base, equip_type_args) = match extract_base_and_args(&recv_ast) {
            Some(pair) => pair,
            None => return,
        };
        let equip_blocks = match self.equip_templates.get(&equip_base) {
            Some(b) => b.clone(),
            None => return,
        };
        // Find the matching method with method-level generic params.
        // First check the equip blocks (explicit overrides); if none match,
        // fall through to default-method bodies on the trait the equip
        // implements (e.g. `bool any[F](&self, F pred)` declared on
        // `trait Iterator[T]:` and inherited by every `equip X with
        // Iterator[T]:` block).
        let mut matched: Option<ast::FunctionDef> = None;
        for equip in &equip_blocks {
            for m in &equip.items {
                if m.node.name.node == method_name.node
                    && m.node.generic_params.as_ref()
                        .map(|gp| gp.node.params.len() == method_targs.len())
                        .unwrap_or(false)
                {
                    matched = Some(m.node.clone());
                    break;
                }
            }
            if matched.is_some() {
                break;
            }
        }
        if matched.is_none() {
            matched = self.find_default_trait_method(
                &equip_blocks, &method_name.node, method_targs.len(),
            );
        }
        if matched.is_none() {
            return;
        }
        let mangled_type = mangle_generic_name(&equip_base, &equip_type_args);
        let mangled_symbol = mangle_method_instance(&mangled_type, &method_name.node, method_targs);
        if self.method_instances_registered.contains_key(&mangled_symbol) {
            return;
        }
        let method_def_for_scan = matched.clone().unwrap();
        // Rescan the method body with the merged substitution applied so any
        // nested generic calls (e.g. `find_iter[T, VectorIter[T], F](self, pred)`
        // inside `.find`) get registered as concrete instances. Without this,
        // `find_iter__int64_t__VectorIter__int64_t__GorgetClosure` is missing
        // from fn_sigs when the call site lowers, and the ret-type lookup
        // falls back to I64 instead of Option[int].
        let equip_blocks = self.equip_templates.get(&equip_base).cloned().unwrap_or_default();
        let mut merged_subs: Vec<(String, Type)> = Vec::new();
        let mut substituted_equipped: Option<Type> = None;
        let mut chosen_equip: Option<&ast::EquipBlock> = None;
        for equip in &equip_blocks {
            let eq_subs = build_equip_type_substitutions(equip, &equip_type_args);
            if !eq_subs.is_empty() {
                substituted_equipped = Some(substitute::substitute_type_pub(&equip.type_.node, &eq_subs));
                merged_subs = eq_subs;
                chosen_equip = Some(equip);
                break;
            }
        }
        // Non-generic equip: equip_subs is empty but we still want
        // Self + trait-T bound against the concrete receiver.
        if chosen_equip.is_none() {
            if let Some(equip) = equip_blocks.first() {
                substituted_equipped = Some(substitute::substitute_type_pub(&equip.type_.node, &merged_subs));
                chosen_equip = Some(equip);
            }
        }
        if let Some(ref gp) = method_def_for_scan.generic_params {
            for (param, arg) in gp.node.params.iter().zip(method_targs.iter()) {
                let name = match &param.node {
                    GenericParam::Type { name: s, .. } => s.node.clone(),
                    GenericParam::Const { name, .. } => name.node.clone(),
                };
                // Method-level generics are the innermost scope and must
                // SHADOW an equip-level param of the same name. Without this,
                // a struct+method sharing a param letter collides: e.g.
                // `equip [Iter, T, F] FilterIter[...]`'s predicate `F` (a
                // `bool(T)` closure) and the trait-default `map[U, F]`'s map
                // closure `F` (a `U(T)` closure) both land in the flat sub
                // list, equip-first. `substitute_type` takes the first match,
                // so the equip `F` (bool) wrongly overrode the method `F`,
                // typing the map result `bool` and byte-truncating the real
                // `int64_t` value at the `Some_0` store. The equipped-type
                // substitution above is already computed from the equip-only
                // subs, so removing the shadowed entry here is safe.
                merged_subs.retain(|(n, _)| n != &name);
                merged_subs.push((name, arg.node.clone()));
            }
        }
        // Bind the trait's own generic params (trait-scope T etc.) first
        // so trait-body refs win over any collision with impl-scope names.
        let mut trait_subs: Vec<(String, Type)> = Vec::new();
        if let Some(equip) = chosen_equip {
            if let Some(ref trait_ref) = equip.trait_ {
                let trait_name = super::traits::extract_trait_name(&trait_ref.trait_name.node);
                if let Some(td) = self.trait_defs.get(&trait_name) {
                    let trait_args: Vec<Type> = if let Type::Named { generic_args, .. } = &trait_ref.trait_name.node {
                        generic_args.iter().map(|a| substitute::substitute_type_pub(&a.node, &merged_subs)).collect()
                    } else {
                        Vec::new()
                    };
                    if let Some(ref gp) = td.generic_params {
                        for (param, concrete) in gp.node.params.iter().zip(trait_args.iter()) {
                            let name = match &param.node {
                                GenericParam::Type { name: s, .. } => s.node.clone(),
                                GenericParam::Const { name: s, .. } => s.node.clone(),
                            };
                            trait_subs.push((name, concrete.clone()));
                        }
                    }
                }
            }
        }
        // Bind `Self` for trait-default bodies whose return type or
        // struct literals mention `Self` (lifted adapter constructors
        // like `FilterIter[Self, T, F] filter[F](self, F p): return
        // FilterIter[Self, T, F](self, p)`). Without this, scan_function
        // sees `FilterIter[SelfType, int, bool(int)]` — the unresolved
        // SelfType trips `type_has_generic_param` (for each equip T) OR
        // falls through as a literal `Self` name that never mangles to
        // a real registered type.
        let final_subs_prefix: Vec<(String, Type)> = {
            let mut v = trait_subs;
            if let Some(ref eq_ty) = substituted_equipped {
                v.push(("Self".to_string(), eq_ty.clone()));
            }
            v
        };
        let mut reordered: Vec<(String, Type)> = Vec::new();
        reordered.extend(final_subs_prefix);
        reordered.extend(merged_subs);
        let merged_subs = reordered;
        if !merged_subs.is_empty() {
            let prev = self.current_generic_params.take();
            let substituted = substitute_function_body(&method_def_for_scan, &merged_subs);
            self.scan_function(&substituted);
            // Also walk the substituted body for nested method-generic
            // calls so transitive registration fires. Without this, a
            // user-space wrapper like `void each[F](self, F f):
            // self.iter().for_each[F](f)` registers `each[F=Closure]`
            // but the inner `for_each[F=Closure]` call stays
            // un-registered — the fn_sigs lookup falls back to the
            // un-mangled `for_each` symbol which is a linker dead end.
            // `method_instances_registered` early-exits on repeats, so
            // recursion is bounded.
            //
            // `self` in the substituted body still has AST type
            // `Type::SelfType` — `populate_env_from_params` can't infer
            // through that. Pre-bind `self` to the concrete equipping
            // type (e.g. `Vector[int]`) so the receiver chain resolves.
            let mut env = LocalTypeEnv::default();
            populate_env_from_params(&mut env, &substituted.params);
            // Override self's binding (populate_env_from_params just set
            // it to `Type::SelfType` from the AST param). Use the
            // concrete equipping type so receiver chains like
            // `self.iter().for_each(...)` resolve through equip_templates.
            let dummy = Span { start: 0, end: 0 };
            env.bind("self".to_string(), Type::Named {
                name: Spanned { node: equip_base.clone(), span: dummy },
                generic_args: equip_type_args.clone(),
            });
            self.walk_fn_body_for_method_calls(&substituted.body, &mut env);
            self.current_generic_params = prev;
        }

        self.method_instances_registered.insert(mangled_symbol.clone(), ());
        self.method_instances.push(MethodInstance {
            equip_base,
            equip_type_args,
            mangled_type,
            method_name: method_name.node.clone(),
            method_type_args: method_targs.to_vec(),
            mangled_symbol,
        });
    }

    /// Discover the return-type struct instance produced by a
    /// non-method-generic trait-default method call. Demand-driven
    /// complement to `try_register_method_instance`: when
    /// `v.iter().take(3)` hits an `Iterator[T]` default with signature
    /// `TakeIter[Self, T] take(self, int n)`, substitute `Self → receiver
    /// type` + impl-level generic params against the receiver's concrete
    /// args, then `scan_type` the substituted return so the resulting
    /// `TakeIter[VectorIter[int], int]` gets registered as a struct
    /// instance ahead of IR lowering.
    ///
    /// Only registers the DIRECT return-type nominal — the newly-registered
    /// instance's own trait defaults stay dormant (avoiding the
    /// `TakeIter[TakeIter[..], int]` infinite cascade).
    fn try_register_default_return_type(
        &mut self,
        receiver: &Spanned<Expr>,
        method_name: &Spanned<String>,
        env: &LocalTypeEnv,
    ) {
        let recv_ast = match self.infer_expr_ast_type(receiver, env) {
            Some(t) => t,
            None => return,
        };
        let (equip_base, equip_type_args) = match extract_base_and_args(&recv_ast) {
            Some(pair) => pair,
            None => return,
        };
        let equip_blocks = match self.equip_templates.get(&equip_base) {
            Some(b) => b.clone(),
            None => return,
        };
        // Skip if any equip block has an inherent (non-generic) override —
        // those already lower via the normal path. We only need
        // registration when the call will dispatch to the trait default.
        for equip in &equip_blocks {
            for m in &equip.items {
                if m.node.name.node == method_name.node
                    && m.node.generic_params.is_none()
                {
                    return;
                }
            }
        }
        // Look up the non-method-generic trait default.
        let default_m = match self.find_default_trait_method(&equip_blocks, &method_name.node, 0) {
            Some(m) => m,
            None => return,
        };
        if default_m.generic_params.is_some() {
            return;
        }
        // Pick the equip block that matches the receiver's template (the
        // one whose subs are non-empty for our type args). Track the chosen
        // block so we can also extract its trait_ref's args for binding the
        // trait's own generic params (`T` in `Iterator[T]` → `(K, V)` for
        // `equip [K, V] DictIter[K, V] with Iterator[(K, V)]`).
        let (equip_type_ast, subs, chosen_equip) = {
            let mut chosen: Option<(Type, Vec<(String, Type)>, &ast::EquipBlock)> = None;
            for eq in &equip_blocks {
                let s = build_equip_type_substitutions(eq, &equip_type_args);
                if !s.is_empty() {
                    chosen = Some((eq.type_.node.clone(), s, eq));
                    break;
                }
            }
            match chosen {
                Some(triple) => triple,
                None => return,
            }
        };
        // Self → concrete equipped type (mirrors the Self binding already
        // threaded through register_equip_sigs_with_defaults and
        // lower_method_instance).
        let substituted_equipped = substitute::substitute_type_pub(&equip_type_ast, &subs);
        let mut full_subs: Vec<(String, Type)> = Vec::new();
        full_subs.push(("Self".to_string(), substituted_equipped));
        // Bind trait-scope generic params (e.g. `T` in `Iterator[T]`) to
        // the equip's substituted trait args (e.g. `(K, V)` for
        // `with Iterator[(K, V)]`). Without this, default-method return
        // types like `TakeIter[Self, T]` substitute to `TakeIter[X, T]`
        // with `T` unresolved — the `scan_type` registration then misses
        // the concrete `TakeIter[X, (int, int)]` instance and the body-
        // emission demand-gate skips `take` for the equipping type.
        if let Some(ref trait_ref) = chosen_equip.trait_ {
            let trait_name = super::traits::extract_trait_name(&trait_ref.trait_name.node);
            if let Some(td) = self.trait_defs.get(&trait_name) {
                let trait_args: Vec<Type> = if let Type::Named { generic_args, .. } = &trait_ref.trait_name.node {
                    generic_args.iter().map(|a| substitute::substitute_type_pub(&a.node, &subs)).collect()
                } else {
                    Vec::new()
                };
                if let Some(ref gp) = td.generic_params {
                    for (param, concrete) in gp.node.params.iter().zip(trait_args.iter()) {
                        let name = match &param.node {
                            GenericParam::Type { name: s, .. } => s.node.clone(),
                            GenericParam::Const { name: s, .. } => s.node.clone(),
                        };
                        full_subs.push((name, concrete.clone()));
                    }
                }
            }
        }
        full_subs.extend(subs.iter().cloned());
        // Substitute the return type AST and scan it so every nominal
        // inside (including nested ones) registers as a struct/enum
        // instance.
        let substituted_ret = substitute::substitute_type_pub(&default_m.return_type.node, &full_subs);
        let spanned_ret = Spanned { node: substituted_ret, span: default_m.return_type.span };
        let prev = self.current_generic_params.take();
        self.scan_type(&spanned_ret);
        self.current_generic_params = prev;
    }

    /// Look for a method-level-generic default trait method matching `name`
    /// on any trait this set of equip blocks implements. Returns the matching
    /// FunctionDef (cloned) when one is found.
    ///
    /// Used by the per-call-site mono path: when the equip block doesn't
    /// override the method, we fall back to the trait's default body so
    /// callers like `v.iter().any[bool(int)](pred)` still resolve when
    /// `any` is declared on `trait Iterator[T]:` and inherited by every
    /// equipping type.
    pub(crate) fn find_default_trait_method(
        &self,
        equip_blocks: &[ast::EquipBlock],
        name: &str,
        method_targs_len: usize,
    ) -> Option<ast::FunctionDef> {
        for equip in equip_blocks {
            let trait_ref = equip.trait_.as_ref()?;
            let trait_name = super::traits::extract_trait_name(&trait_ref.trait_name.node);
            if trait_name.is_empty() {
                continue;
            }
            let trait_def = match self.trait_defs.get(&trait_name) {
                Some(td) => td,
                None => continue,
            };
            // Skip default methods overridden in this equip block.
            for trait_item in &trait_def.items {
                if let ast::TraitItem::Method(m) = &trait_item.node {
                    if m.name.node != name { continue; }
                    let gp_len = m.generic_params.as_ref()
                        .map(|gp| gp.node.params.len()).unwrap_or(0);
                    if gp_len != method_targs_len { continue; }
                    if matches!(m.body, ast::FunctionBody::Declaration | ast::FunctionBody::Extern(_)) {
                        continue;
                    }
                    let overridden = equip.items.iter()
                        .any(|im| im.node.name.node == name);
                    if overridden { continue; }
                    return Some(m.clone());
                }
            }
        }
        None
    }

    /// Best-effort AST-level type inference for MethodCall discovery. Does NOT
    /// implement full Hindley-Milner — just enough to resolve chains like
    /// `v.iter().take(n).map[U, F](f)` where each step can be resolved by
    /// looking up the previous step's type in `equip_templates` and
    /// substituting through the equip block's method return type.
    fn infer_expr_ast_type(&self, expr: &Spanned<Expr>, env: &LocalTypeEnv) -> Option<Type> {
        match &expr.node {
            Expr::Identifier(name) => env.lookup(name).cloned(),
            Expr::SelfExpr => env.lookup("self").cloned(),
            Expr::MethodCall { receiver, method, generic_args, .. } => {
                let recv_ty = self.infer_expr_ast_type(receiver, env)?;
                let (base, args) = extract_base_and_args(&recv_ty)?;
                let equip_blocks = self.equip_templates.get(&base)?;
                // Find a method matching name + generic-arg arity. We prefer
                // the first match; equip blocks with the same method name at
                // different arities don't collide (that'd be a duplicate-impl
                // error caught by typecheck).
                for equip in equip_blocks {
                    for m in &equip.items {
                        let gp_len = m.node.generic_params.as_ref()
                            .map(|gp| gp.node.params.len())
                            .unwrap_or(0);
                        let targs_len = generic_args.as_ref().map(|g| g.len()).unwrap_or(0);
                        if m.node.name.node != method.node || gp_len != targs_len {
                            continue;
                        }
                        let mut subs = build_equip_type_substitutions(equip, &args);
                        if let (Some(gp), Some(targs)) = (m.node.generic_params.as_ref(), generic_args.as_ref()) {
                            for (param, arg) in gp.node.params.iter().zip(targs.iter()) {
                                let name = match &param.node {
                                    GenericParam::Type { name: s, .. } => s.node.clone(),
                                    GenericParam::Const { name, .. } => name.node.clone(),
                                };
                                subs.push((name, arg.node.clone()));
                            }
                        }
                        return Some(substitute::substitute_type_pub(&m.node.return_type.node, &subs));
                    }
                }
                // Fall through to trait-default resolution. With adapter
                // constructors lifted to `Iterator[T]` defaults
                // (`TakeIter[Self, T] take(self, int n)`), inherent equip
                // blocks don't carry them anymore — the chain inference
                // above misses. Look up the default method on the trait
                // the equip block implements and substitute against the
                // receiver's concrete args.
                let targs_len = generic_args.as_ref().map(|g| g.len()).unwrap_or(0);
                let default_m = self.find_default_trait_method(equip_blocks, &method.node, targs_len)?;
                // Build subs: impl locals from receiver, method generics
                // from the call's targs, plus Self → receiver.
                let (equip_ty, eq_subs) = {
                    let mut chosen: Option<(Type, Vec<(String, Type)>)> = None;
                    for eq in equip_blocks {
                        let s = build_equip_type_substitutions(eq, &args);
                        if !s.is_empty() {
                            chosen = Some((eq.type_.node.clone(), s));
                            break;
                        }
                    }
                    chosen?
                };
                let mut subs = eq_subs;
                if let (Some(gp), Some(targs)) = (default_m.generic_params.as_ref(), generic_args.as_ref()) {
                    for (param, arg) in gp.node.params.iter().zip(targs.iter()) {
                        let name = match &param.node {
                            GenericParam::Type { name: s, .. } => s.node.clone(),
                            GenericParam::Const { name, .. } => name.node.clone(),
                        };
                        subs.push((name, arg.node.clone()));
                    }
                }
                let substituted_equipped = substitute::substitute_type_pub(&equip_ty, &subs);
                subs.push(("Self".to_string(), substituted_equipped));
                Some(substitute::substitute_type_pub(&default_m.return_type.node, &subs))
            }
            Expr::Call { callee, generic_args, .. } => {
                // Free-function call: look up the fn template and substitute the return type
                // using the call-site type args. Only covers simple `foo[T](args)` shapes.
                if let Expr::Identifier(name) = &callee.node {
                    if let Some(tmpl) = self.fn_templates.get(name) {
                        let mut subs = Vec::new();
                        if let (Some(gp), Some(targs)) = (tmpl.generic_params.as_ref(), generic_args.as_ref()) {
                            for (param, arg) in gp.node.params.iter().zip(targs.iter()) {
                                let pname = match &param.node {
                                    GenericParam::Type { name: s, .. } => s.node.clone(),
                                    GenericParam::Const { name, .. } => name.node.clone(),
                                };
                                subs.push((pname, arg.node.clone()));
                            }
                        }
                        return Some(substitute::substitute_type_pub(&tmpl.return_type.node, &subs));
                    }
                }
                None
            }
            Expr::StructLiteral { name, generic_args, .. } => {
                let targs = generic_args.as_ref().cloned().unwrap_or_default();
                Some(Type::Named { name: name.clone(), generic_args: targs })
            }
            _ => None,
        }
    }

    /// Accessor for sig registration + body lowering.
    pub fn method_instances(&self) -> &[MethodInstance] {
        &self.method_instances
    }

    /// Predict the mangled symbol for a MethodCall with generic args. Used by
    /// call-site dispatch to rewrite `v.iter().map[...](...)` into a direct
    /// call to the specialised free-function symbol. Returns `None` when no
    /// matching instance has been registered (caller falls back to the
    /// existing dispatch path).
    pub fn lookup_method_instance_symbol(
        &self,
        equip_base: &str,
        equip_type_args: &[Spanned<Type>],
        method_name: &str,
        method_type_args: &[Spanned<Type>],
    ) -> Option<String> {
        let mangled_type = mangle_generic_name(equip_base, equip_type_args);
        let mangled_symbol = mangle_method_instance(&mangled_type, method_name, method_type_args);
        if self.method_instances_registered.contains_key(&mangled_symbol) {
            Some(mangled_symbol)
        } else {
            None
        }
    }

    /// Phase 3: Monomorphize all discovered instantiations.
    /// Creates TypeDefs for generic structs/enums and registers them in TypeMapper/TypeRegistry.
    ///
    /// The instance order is discovery order (type annotations first, then
    /// transitively through bodies). That order can have forward references:
    /// `TakeIter[int]` (seen from a let-type annotation) gets registered
    /// before `VectorIter[int]` (only discovered via Vector's iter() equip
    /// method body), yet `TakeIter[T]` has `inner: VectorIter[T]`. On the
    /// first pass, TakeIter[int]'s field resolves to UNIT_TYPE because
    /// VectorIter[int] isn't in `named_types` yet.
    ///
    /// We fix this by running the struct/enum monomorphization pass twice.
    /// The first pass registers every user-generic struct/enum name (even
    /// if some fields are UNIT_TYPE). The second pass overwrites each
    /// TypeDef with correctly-resolved fields now that all names are
    /// available.
    ///
    /// Two passes is enough for any DAG — circular references between
    /// user generic structs would be a separate design issue (they'd need
    /// pointer-indirection anyway to terminate the layout). Option / Result
    /// and Collection aliases are single-pass (their TypeDefs depend only
    /// on their type args, which resolve immediately).
    pub fn monomorphize_types(
        &self,
        mapper: &mut TypeMapper,
        registry: &mut TypeRegistry,
    ) {
        // First pass: register names (fields may have forward-ref UNIT_TYPE).
        self.monomorphize_types_once(mapper, registry, /*force_rebuild=*/ false);
        // Second pass: re-build user struct/enum TypeDefs with all names now
        // in `named_types`. Forward references resolve correctly this time.
        self.monomorphize_types_once(mapper, registry, /*force_rebuild=*/ true);
    }

    fn monomorphize_types_once(
        &self,
        mapper: &mut TypeMapper,
        registry: &mut TypeRegistry,
        force_rebuild: bool,
    ) {
        for (base_name, type_args, mangled_name, kind) in &self.instances {
            // Runtime collection types (Vector, Dict, etc.) are declared as
            // `struct Vector[T]: pass` in std.collections so they land in
            // `struct_templates`, but their real layout is the opaque
            // GorgetArray / GorgetMap / … runtime structs. Skip the
            // second-pass rebuild for them — their "fields" are always
            // empty anyway, and re-running the rebuild has been observed
            // to perturb downstream FieldPtr resolution on unrelated
            // types (self-host lowerer hits `FieldPtr on Str` OOB without
            // this guard).
            let is_runtime_collection = matches!(
                base_name.as_str(),
                "Vector" | "Deque" | "Dict" | "HashMap" | "Set" | "HashSet" | "Box"
                    | "Channel" | "RWLock" | "Shared" | "Weak" | "Heap"
                    | "Mutex" | "Guard" | "ReadGuard" | "WriteGuard"
            );
            match kind {
                TemplateKind::Struct => {
                    if let Some(template) = self.struct_templates.get(base_name) {
                        if force_rebuild {
                            if !is_runtime_collection {
                                remonomorphize_struct_fields(template, type_args, mangled_name, mapper, registry);
                            }
                        } else {
                            monomorphize_struct(template, type_args, mangled_name, mapper, registry);
                        }
                    } else if is_runtime_collection {
                        // Runtime collection types — no template to monomorphize, register alias
                        if !mapper.named_types.contains_key(mangled_name) {
                            super::types::register_collection_alias(mapper, registry, base_name, type_args, mangled_name);
                        }
                    }
                }
                TemplateKind::Enum => {
                    if let Some(template) = self.enum_templates.get(base_name) {
                        if force_rebuild {
                            remonomorphize_enum_fields(template, type_args, mangled_name, mapper, registry);
                        } else {
                            monomorphize_enum(template, type_args, mangled_name, mapper, registry);
                        }
                    }
                }
                TemplateKind::Function => {
                    // Function signatures are registered separately
                }
            }
        }
    }

    /// Register monomorphized function signatures in the fn_sigs map.
    pub fn register_fn_sigs(
        &self,
        mapper: &TypeMapper,
        registry: &mut TypeRegistry,
        fn_sigs: &mut FxHashMap<String, (Vec<TypeId>, TypeId)>,
        fn_param_ownerships: &mut FxHashMap<String, Vec<crate::parser::ast::Ownership>>,
        fn_param_abis: &mut FxHashMap<String, Vec<super::context::ParamABI>>,
    ) {
        use crate::parser::ast::{Ownership, FunctionBody};
        for (base_name, type_args, mangled_name, kind) in &self.instances {
            if !matches!(kind, TemplateKind::Function) {
                continue;
            }
            if let Some(template) = self.fn_templates.get(base_name) {
                let subs = build_type_substitutions(template.generic_params.as_ref(), type_args);
                let ret_type = substitute_and_map(mapper, &template.return_type.node, &subs);

                // Detect bare Move-type params that are directly returned.
                // Upgrade these from Borrow to Move to prevent double-free.
                let mut move_override_params: std::collections::HashSet<String> = std::collections::HashSet::new();
                if registry.is_resource_type(ret_type) {
                    let returned_param_name = match &template.body {
                        FunctionBody::Expression(expr) => {
                            if let Expr::Identifier(name) = &expr.node {
                                Some(name.as_str())
                            } else { None }
                        }
                        FunctionBody::Block(block) => {
                            if block.stmts.len() == 1 {
                                if let Stmt::Return(Some(expr)) = &block.stmts[0].node {
                                    if let Expr::Identifier(name) = &expr.node {
                                        Some(name.as_str())
                                    } else { None }
                                } else { None }
                            } else { None }
                        }
                        _ => None,
                    };
                    if let Some(name) = returned_param_name {
                        for p in &template.params {
                            if !p.node.is_meta_op
                                && p.node.name.node == name
                                && p.node.ownership == Ownership::Borrow
                            {
                                let base = substitute_and_map(mapper, &p.node.type_.node, &subs);
                                if registry.is_resource_type(base) {
                                    move_override_params.insert(name.to_string());
                                }
                            }
                        }
                    }
                }

                let param_types: Vec<TypeId> = template.params.iter()
                    .filter(|p| !p.node.is_meta_op) // meta op params have no runtime slot
                    .map(|p| {
                        let base = substitute_and_map(mapper, &p.node.type_.node, &subs);
                        // MutableBorrow params become MutPtr in the GIR
                        if matches!(p.node.ownership, Ownership::MutableBorrow) {
                            registry.insert(GirType::MutPtr(base))
                        } else {
                            base
                        }
                    })
                    .collect();

                // Register param ownerships so lower_call_arg uses correct semantics
                let param_ownerships: Vec<Ownership> = template.params.iter()
                    .filter(|p| !p.node.is_meta_op)
                    .map(|p| {
                        if move_override_params.contains(&p.node.name.node) {
                            Ownership::Move
                        } else {
                            p.node.ownership
                        }
                    })
                    .collect();

                // Compute ParamABI for monomorphized generic functions
                let abis: Vec<super::context::ParamABI> = template.params.iter()
                    .filter(|p| !p.node.is_meta_op)
                    .map(|p| {
                        let ownership = if move_override_params.contains(&p.node.name.node) {
                            Ownership::Move
                        } else {
                            p.node.ownership
                        };
                        let base = substitute_and_map(mapper, &p.node.type_.node, &subs);
                        let is_move = registry.is_resource_type(base);
                        match ownership {
                            Ownership::MutableBorrow => super::context::ParamABI::ByMutPtr,
                            Ownership::Move if is_move => super::context::ParamABI::ByMutPtr,
                            Ownership::Borrow if is_move => super::context::ParamABI::ByPtr,
                            _ => super::context::ParamABI::ByValue,
                        }
                    })
                    .collect();

                fn_sigs.insert(mangled_name.clone(), (param_types, ret_type));
                fn_param_ownerships.insert(mangled_name.clone(), param_ownerships);
                fn_param_abis.insert(mangled_name.clone(), abis);
            }
        }
    }

    /// Register monomorphized equip method signatures.
    pub fn register_equip_sigs(
        &self,
        mapper: &mut TypeMapper,
        registry: &mut TypeRegistry,
        fn_sigs: &mut FxHashMap<String, (Vec<TypeId>, TypeId)>,
        fn_param_abis: &mut FxHashMap<String, Vec<super::context::ParamABI>>,
    ) {
        let mut throwaway = FxHashMap::default();
        self.register_equip_sigs_with_defaults(mapper, registry, fn_sigs, fn_param_abis, &mut throwaway, None);
    }

    /// Register monomorphized equip method signatures, including default trait methods.
    ///
    /// Uses the mutable mapper (`substitute_and_map_mut`) so that return types like
    /// `Option[double]` are auto-registered in the type registry if not already present.
    /// Without this, return types that haven't been discovered yet resolve to UNIT_TYPE,
    /// causing the IR to emit void calls and silently discard the result.
    pub fn register_equip_sigs_with_defaults(
        &self,
        mapper: &mut TypeMapper,
        registry: &mut TypeRegistry,
        fn_sigs: &mut FxHashMap<String, (Vec<TypeId>, TypeId)>,
        fn_param_abis: &mut FxHashMap<String, Vec<super::context::ParamABI>>,
        fn_param_ownerships: &mut FxHashMap<String, Vec<crate::parser::ast::Ownership>>,
        ast_module: Option<&crate::parser::ast::Module>,
    ) {
        use crate::parser::ast::{Item, Ownership, TraitItem, FunctionBody};
        for (base_name, type_args, mangled_type_name, kind) in &self.instances {
            if !matches!(kind, TemplateKind::Struct | TemplateKind::Enum) {
                continue;
            }
            if let Some(equip_blocks) = self.equip_templates.get(base_name) {
                let equip_blocks = equip_blocks.clone();
                for equip in &equip_blocks {
                    let subs = build_equip_type_substitutions(equip, type_args);
                    let mut implemented = Vec::new();
                    for method in &equip.items {
                        // Methods with their own generic params — e.g.
                        // `MapIter[T, U, F] map[U, F](self, F f)` — can't be
                        // fully resolved from the equip-level substitutions
                        // alone. The `T→int64_t` sub covers the struct param
                        // but U and F stay abstract, so feeding the return
                        // type through `substitute_and_map_mut` would mangle
                        // it to `MapIter__int64_t__U__F` and accidentally
                        // register that as a concrete struct (with `F f`
                        // becoming `void f`). The per-call-site monomorphizer
                        // handles these correctly — skip the eager sig
                        // registration here.
                        if method.node.generic_params.is_some() {
                            continue;
                        }
                        let method_mangled = format!("{mangled_type_name}__{}", method.node.name.node);
                        let ret_type = substitute_and_map_mut(mapper, registry, &method.node.return_type.node, &subs);
                        let has_self = method.node.params.first()
                            .map(|p| p.node.name.node == "self")
                            .unwrap_or(false);
                        let mut param_types = Vec::new();
                        let mut abis = Vec::new();
                        if has_self {
                            let self_type_id = mapper.lookup_named(mangled_type_name).unwrap_or(UNIT_TYPE);
                            let self_needs_mut_ptr = method.node.params.first()
                                .map(|p| matches!(p.node.ownership, Ownership::MutableBorrow | Ownership::Move))
                                .unwrap_or(false);
                            let self_ptr_type = if self_needs_mut_ptr {
                                registry.insert(GirType::MutPtr(self_type_id))
                            } else {
                                registry.insert(GirType::Ptr(self_type_id))
                            };
                            param_types.push(self_ptr_type);
                            abis.push(if self_needs_mut_ptr {
                                super::context::ParamABI::ByMutPtr
                            } else {
                                super::context::ParamABI::ByPtr
                            });
                        }
                        for p in &method.node.params {
                            if p.node.name.node == "self" {
                                continue;
                            }
                            let base = substitute_and_map_mut(mapper, registry, &p.node.type_.node, &subs);
                            param_types.push(base);
                            let is_move = registry.is_resource_type(base);
                            abis.push(match p.node.ownership {
                                Ownership::MutableBorrow => super::context::ParamABI::ByMutPtr,
                                Ownership::Move if is_move => super::context::ParamABI::ByMutPtr,
                                Ownership::Borrow if is_move => super::context::ParamABI::ByPtr,
                                _ => super::context::ParamABI::ByValue,
                            });
                        }
                        // Param ownerships including self (for !-self MoveZero
                        // at the call site — see lower_method_call's
                        // `has_consuming_self`).
                        let mut method_ownerships: Vec<crate::parser::ast::Ownership> = Vec::new();
                        if has_self {
                            method_ownerships.push(method.node.params.first()
                                .map(|p| p.node.ownership)
                                .unwrap_or(crate::parser::ast::Ownership::Borrow));
                        }
                        for p in &method.node.params {
                            if p.node.name.node == "self" {
                                continue;
                            }
                            method_ownerships.push(p.node.ownership);
                        }
                        fn_sigs.insert(method_mangled.clone(), (param_types, ret_type));
                        fn_param_abis.insert(method_mangled.clone(), abis);
                        fn_param_ownerships.insert(method_mangled, method_ownerships);
                        implemented.push(method.node.name.node.clone());
                    }
                    // Also register signatures for default trait methods
                    if let (Some(ast_mod), Some(trait_ref)) = (ast_module, &equip.trait_) {
                        let trait_name = super::traits::extract_trait_name(&trait_ref.trait_name.node);
                        if !trait_name.is_empty() {
                            // Default method bodies reference `Self` as the
                            // equipping iterator (e.g.
                            // `TakeIter[Self, T] take(self, int n)`) and
                            // the TRAIT's own generic params (e.g. `T` in
                            // `Vector[T] collect(&self)` on `Iterator[T]`).
                            // Substitute Self → mono'd equipped type and
                            // each trait generic param → corresponding
                            // substituted trait arg. When impl generics
                            // and trait generics share a name (e.g.
                            // `equip [Iter, T, U, F] MapIter[...] with
                            // Iterator[U]` has a local T AND the trait
                            // has its own T that maps to U), the trait-
                            // scope binding wins for trait-body refs —
                            // push trait bindings BEFORE impl subs in the
                            // lookup order (first-match wins).
                            let substituted_equipped = substitute::substitute_type_pub(&equip.type_.node, &subs);
                            // Extract trait generic args from the trait
                            // annotation and substitute impl subs through
                            // them so they reduce to concrete types.
                            let trait_args: Vec<crate::parser::ast::Type> = if let crate::parser::ast::Type::Named { generic_args, .. } = &trait_ref.trait_name.node {
                                generic_args.iter()
                                    .map(|a| substitute::substitute_type_pub(&a.node, &subs))
                                    .collect()
                            } else {
                                Vec::new()
                            };
                            // Look up the trait to get its own generic param
                            // names (e.g. `[T]` for `trait Iterator[T]`).
                            let trait_generic_names: Vec<String> = ast_mod.items.iter()
                                .find_map(|it| {
                                    if let Item::Trait(td) = &it.node {
                                        if td.name.node == trait_name {
                                            return td.generic_params.as_ref().map(|gp| {
                                                gp.node.params.iter().filter_map(|p| match &p.node {
                                                    GenericParam::Type { name, .. } => Some(name.node.clone()),
                                                    GenericParam::Const { .. } => None,
                                                }).collect()
                                            });
                                        }
                                    }
                                    None
                                })
                                .unwrap_or_default();
                            let mut default_subs: Vec<(String, crate::parser::ast::Type)> = Vec::new();
                            default_subs.push(("Self".to_string(), substituted_equipped));
                            for (name, concrete) in trait_generic_names.iter().zip(trait_args.iter()) {
                                default_subs.push((name.clone(), concrete.clone()));
                            }
                            default_subs.extend(subs.iter().cloned());
                            for item in &ast_mod.items {
                                if let Item::Trait(trait_def) = &item.node {
                                    if trait_def.name.node == trait_name {
                                        for trait_item in &trait_def.items {
                                            if let TraitItem::Method(dm) = &trait_item.node {
                                                if implemented.contains(&dm.name.node) { continue; }
                                                match &dm.body {
                                                    FunctionBody::Declaration | FunctionBody::Extern(_) => continue,
                                                    _ => {}
                                                }
                                                // Method-level generics (`map[U, F]`) go
                                                // through register_method_instance_sigs instead.
                                                if dm.generic_params.is_some() {
                                                    continue;
                                                }
                                                let m_mangled = format!("{mangled_type_name}__{}", dm.name.node);
                                                let ret_type = substitute_and_map_mut(mapper, registry, &dm.return_type.node, &default_subs);
                                                let self_type_id = mapper.lookup_named(mangled_type_name).unwrap_or(UNIT_TYPE);
                                                let self_needs_mut_ptr = dm.params.first()
                                                    .map(|p| matches!(p.node.ownership, Ownership::MutableBorrow | Ownership::Move))
                                                    .unwrap_or(false);
                                                let self_ptr_type = if self_needs_mut_ptr {
                                                    registry.insert(GirType::MutPtr(self_type_id))
                                                } else {
                                                    registry.insert(GirType::Ptr(self_type_id))
                                                };
                                                let mut param_types = vec![self_ptr_type];
                                                let mut abis = vec![if self_needs_mut_ptr {
                                                    super::context::ParamABI::ByMutPtr
                                                } else {
                                                    super::context::ParamABI::ByPtr
                                                }];
                                                for p in &dm.params {
                                                    if p.node.name.node == "self" { continue; }
                                                    let base = substitute_and_map_mut(mapper, registry, &p.node.type_.node, &default_subs);
                                                    param_types.push(base);
                                                    let is_move = registry.is_resource_type(base);
                                                    abis.push(match p.node.ownership {
                                                        Ownership::MutableBorrow => super::context::ParamABI::ByMutPtr,
                                                        Ownership::Move if is_move => super::context::ParamABI::ByMutPtr,
                                                        Ownership::Borrow if is_move => super::context::ParamABI::ByPtr,
                                                        _ => super::context::ParamABI::ByValue,
                                                    });
                                                }
                                                let mut default_ownerships: Vec<Ownership> = Vec::new();
                                                if dm.params.first().map(|p| p.node.name.node == "self").unwrap_or(false) {
                                                    default_ownerships.push(dm.params[0].node.ownership);
                                                }
                                                for p in &dm.params {
                                                    if p.node.name.node == "self" { continue; }
                                                    default_ownerships.push(p.node.ownership);
                                                }
                                                fn_sigs.insert(m_mangled.clone(), (param_types, ret_type));
                                                fn_param_abis.insert(m_mangled.clone(), abis);
                                                fn_param_ownerships.insert(m_mangled, default_ownerships);
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    /// Register signatures for per-call-site method instances. Mirrors the
    /// signature-registration half of `register_equip_sigs_with_defaults`
    /// but per-`MethodInstance` with merged equip+method substitutions, and
    /// targets the custom mangled symbol instead of the generic
    /// `{TypeName}__{method_name}` shape.
    pub fn register_method_instance_sigs(
        &self,
        mapper: &mut TypeMapper,
        registry: &mut TypeRegistry,
        fn_sigs: &mut FxHashMap<String, (Vec<TypeId>, TypeId)>,
        fn_param_ownerships: &mut FxHashMap<String, Vec<ast::Ownership>>,
        fn_param_abis: &mut FxHashMap<String, Vec<super::context::ParamABI>>,
    ) {
        use crate::parser::ast::Ownership;
        for mi in &self.method_instances {
            let equip_blocks = match self.equip_templates.get(&mi.equip_base) {
                Some(b) => b,
                None => continue,
            };
            // Find the matching equip + method AST pair. Falls through to
            // the trait's default body when the equip block doesn't override.
            // Defaults aren't held by the equip block, so we own a clone here.
            let mut found_equip: Option<&ast::EquipBlock> = None;
            let mut found_method: Option<ast::FunctionDef> = None;
            for equip in equip_blocks {
                for m in &equip.items {
                    if m.node.name.node == mi.method_name
                        && m.node.generic_params.as_ref()
                            .map(|gp| gp.node.params.len() == mi.method_type_args.len())
                            .unwrap_or(false)
                    {
                        found_equip = Some(equip);
                        found_method = Some(m.node.clone());
                        break;
                    }
                }
                if found_method.is_some() {
                    break;
                }
            }
            if found_method.is_none() {
                if let Some(default_m) = self.find_default_trait_method(
                    equip_blocks, &mi.method_name, mi.method_type_args.len(),
                ) {
                    if let Some(eq) = equip_blocks.first() {
                        found_equip = Some(eq);
                        found_method = Some(default_m);
                    }
                }
            }
            let equip = match found_equip {
                Some(e) => e,
                None => continue,
            };
            let method = match found_method.as_ref() {
                Some(m) => m,
                None => continue,
            };

            // Merged subs: equip-level (T → from receiver) + method-level (U, F → from call-site).
            let mut subs = build_equip_type_substitutions(equip, &mi.equip_type_args);
            // Bind `Self` so trait-default sigs like
            // `MapIter[Self, T, U, F] map[U, F](self, F f)` resolve to
            // the equipping iterator's concrete type in the registered
            // fn_sig. Without this, Self stays literal and mangles to
            // `MapIter__unknown__...` while the body lowering (which
            // also binds Self, see lower_method_instance) emits
            // `MapIter__VectorIter__int64_t__...`, producing a sig/body
            // type mismatch at the call site. Computed from equip-only
            // subs (before the method-param merge below) so method-scope
            // shadowing can't rewrite the receiver's own closure param.
            let substituted_equipped = substitute::substitute_type_pub(&equip.type_.node, &subs);
            if let Some(ref gp) = method.generic_params {
                for (param, arg) in gp.node.params.iter().zip(mi.method_type_args.iter()) {
                    let name = match &param.node {
                        GenericParam::Type { name: s, .. } => s.node.clone(),
                        GenericParam::Const { name, .. } => name.node.clone(),
                    };
                    // Method-level generics shadow equip-level params of the
                    // same name (innermost scope wins). See the matching note
                    // in `try_register_method_instance` — a shared `F` between
                    // the receiver struct's closure and the method's closure
                    // otherwise resolves to the wrong signature.
                    subs.retain(|(n, _)| n != &name);
                    subs.push((name, arg.node.clone()));
                }
            }
            // Also bind the trait's own generic params to their
            // substituted concrete values (e.g. impl's `Iterator[int]`
            // binds trait's `T → int`). Pushed BEFORE Self + impl subs
            // so trait-scope refs win when names collide with impl-
            // scope names. Required for method-generic defaults on
            // non-generic impls (`equip CounterIter with Iterator[int]:`
            // → `fold[A, F]` body references trait's `T`).
            let mut merged: Vec<(String, crate::parser::ast::Type)> = Vec::new();
            if let Some(ref trait_ref) = equip.trait_ {
                let trait_name = super::traits::extract_trait_name(&trait_ref.trait_name.node);
                if let Some(td) = self.trait_defs.get(&trait_name) {
                    let trait_args: Vec<Type> = if let Type::Named { generic_args, .. } = &trait_ref.trait_name.node {
                        generic_args.iter().map(|a| substitute::substitute_type_pub(&a.node, &subs)).collect()
                    } else {
                        Vec::new()
                    };
                    if let Some(ref gp) = td.generic_params {
                        for (param, concrete) in gp.node.params.iter().zip(trait_args.iter()) {
                            let name = match &param.node {
                                GenericParam::Type { name: s, .. } => s.node.clone(),
                                GenericParam::Const { name: s, .. } => s.node.clone(),
                            };
                            merged.push((name, concrete.clone()));
                        }
                    }
                }
            }
            merged.push(("Self".to_string(), substituted_equipped));
            merged.extend(subs.into_iter());
            let subs = merged;

            let ret_type = substitute_and_map_mut(mapper, registry, &method.return_type.node, &subs);
            let has_self = method.params.first()
                .map(|p| p.node.name.node == "self")
                .unwrap_or(false);

            let mut param_types: Vec<TypeId> = Vec::new();
            let mut abis: Vec<super::context::ParamABI> = Vec::new();
            let mut ownerships: Vec<Ownership> = Vec::new();

            if has_self {
                let self_tid = mapper.lookup_named(&mi.mangled_type).unwrap_or(UNIT_TYPE);
                let self_is_mut = method.params.first()
                    .map(|p| matches!(p.node.ownership, Ownership::MutableBorrow | Ownership::Move))
                    .unwrap_or(false);
                let self_ptr = if self_is_mut {
                    registry.insert(GirType::MutPtr(self_tid))
                } else {
                    registry.insert(GirType::Ptr(self_tid))
                };
                param_types.push(self_ptr);
                abis.push(if self_is_mut {
                    super::context::ParamABI::ByMutPtr
                } else {
                    super::context::ParamABI::ByPtr
                });
                ownerships.push(method.params.first().map(|p| p.node.ownership).unwrap_or(Ownership::Borrow));
            }
            for p in &method.params {
                if p.node.name.node == "self" {
                    continue;
                }
                // Use the immutable mapper for param types: it returns UNIT_TYPE
                // for `Type::Function { .. }` which the C backend emits as
                // `void*` (the closure pointer ABI used by free-function
                // closure params like `fold_iter[..., F](F f)`). The mutable
                // mapper would produce a concrete `FnPtr` TypeId, which the
                // body lowering then tries to treat as an owned value and
                // mis-assembles struct-field inits.
                let base = substitute_and_map(mapper, &p.node.type_.node, &subs);
                let final_param_type = if matches!(p.node.ownership, Ownership::MutableBorrow) {
                    registry.insert(GirType::MutPtr(base))
                } else {
                    base
                };
                param_types.push(final_param_type);
                let is_move = registry.is_resource_type(base);
                abis.push(match p.node.ownership {
                    Ownership::MutableBorrow => super::context::ParamABI::ByMutPtr,
                    Ownership::Move if is_move => super::context::ParamABI::ByMutPtr,
                    Ownership::Borrow if is_move => super::context::ParamABI::ByPtr,
                    _ => super::context::ParamABI::ByValue,
                });
                ownerships.push(p.node.ownership);
            }

            fn_sigs.insert(mi.mangled_symbol.clone(), (param_types, ret_type));
            fn_param_abis.insert(mi.mangled_symbol.clone(), abis);
            fn_param_ownerships.insert(mi.mangled_symbol.clone(), ownerships);
        }
    }

    /// Get all discovered function instantiations for lowering.
    pub fn function_instances(&self) -> Vec<(&str, &[Spanned<Type>], &str)> {
        self.instances.iter()
            .filter(|(_, _, _, kind)| matches!(kind, TemplateKind::Function))
            .map(|(base, args, mangled, _)| (base.as_str(), args.as_slice(), mangled.as_str()))
            .collect()
    }

    /// Get all struct/enum instantiations that have equip blocks.
    pub fn equip_instances(&self) -> Vec<(&str, &[Spanned<Type>], &str)> {
        self.instances.iter()
            .filter(|(base, _, _, kind)| {
                matches!(kind, TemplateKind::Struct | TemplateKind::Enum)
                    && self.equip_templates.contains_key(base.as_str())
            })
            .map(|(base, args, mangled, _)| (base.as_str(), args.as_slice(), mangled.as_str()))
            .collect()
    }

    /// Look up a generic function template.
    pub fn get_fn_template(&self, name: &str) -> Option<&ast::FunctionDef> {
        self.fn_templates.get(name)
    }

    /// Look up generic equip templates for a base type name.
    pub fn get_equip_templates(&self, base_name: &str) -> Option<&Vec<ast::EquipBlock>> {
        self.equip_templates.get(base_name)
    }

    /// Get raw access to all instances for iteration.
    pub fn instances_raw(&self) -> &[(String, Vec<Spanned<Type>>, String, TemplateKind)] {
        &self.instances
    }

    /// Get all type instances (struct + enum) with their mangled names.
    pub fn type_instances(&self) -> Vec<(&str, &str)> {
        self.instances.iter()
            .filter(|(_, _, _, kind)| matches!(kind, TemplateKind::Struct | TemplateKind::Enum))
            .map(|(_, _, mangled, _)| {
                let base = self.instances.iter()
                    .find(|(_, _, m, _)| m == mangled)
                    .map(|(b, _, _, _)| b.as_str())
                    .unwrap_or("");
                (base, mangled.as_str())
            })
            .collect()
    }
}

/// Public entry point for on-demand monomorphization of a generic type.
/// Used when struct fields reference generic types that haven't been registered yet.
pub fn monomorphize_generic_type(
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
    template_item: &ast::Item,
    type_args: &[Spanned<Type>],
    mangled_name: &str,
) {
    match template_item {
        ast::Item::Struct(struct_def) => {
            monomorphize_struct(struct_def, type_args, mangled_name, mapper, registry);
        }
        ast::Item::Enum(enum_def) => {
            monomorphize_enum(enum_def, type_args, mangled_name, mapper, registry);
        }
        _ => {}
    }
}

/// Monomorphize a generic struct: create a TypeDef with substituted field types.
fn monomorphize_struct(
    template: &ast::StructDef,
    type_args: &[Spanned<Type>],
    mangled_name: &str,
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
) {
    // Already registered?
    if mapper.named_types.contains_key(mangled_name) {
        return;
    }

    let subs = build_type_substitutions(template.generic_params.as_ref(), type_args);

    let mut fields: Vec<StructField> = Vec::new();
    for f in &template.fields {
        let field_type = substitute_and_map_mut(mapper, registry, &f.node.type_.node, &subs);
        fields.push(StructField {
            name: f.node.name.node.clone(),
            type_id: field_type,
        });
    }

    // Box[T] in std/collections.gg is declared as `struct Box[T]: pass` — its
    // real layout (heap pointer wrapping a T) is compiler-magic. Synthesize the
    // canonical `_0: T` field here so downstream sizing (`c_sizeof_with_structs`
    // → `c_sizeof_struct_def`) sees a non-empty struct and the LIR pre-pass can
    // recognize it as a regular box (`is_regular_box` check in
    // `src/lir/lower/mod.rs:lower_type_defs`) and register it with the
    // hardcoded `_0: Ptr` (8-byte pointer) layout. Without this, the
    // monomorphized Box[T] ends up as a 0-field struct and any caller that
    // sizes its element via `c_sizeof_with_structs` (e.g.,
    // `gorget_array_new(elem_size)` for `Vector[Box[T]]`) gets `0`, producing
    // a 0-byte heap buffer that aliases other allocations on push.
    //
    // Skip this for trait boxes (Box[Trait] where {Trait}_TraitObj exists) —
    // they get a different layout via the LIR's standard two-pass struct
    // registration so the {data, vtable} fields land on the LIR struct.
    if template.name.node == "Box" && !type_args.is_empty() && fields.is_empty() {
        // A trait inner can present several ways: (a) the bare trait name
        // (`Greeter`) — `Greeter_TraitObj` is registered in the GIR registry;
        // (b) the trait-obj struct already (`Greeter_TraitObj`) — name ends
        // in `_TraitObj`; (c) an unresolved trait the mapper falls back to
        // `Unit` for — detected from the AST `Named.name` node (most common
        // since trait types aren't first-class in the type mapper). All three
        // patterns mean "don't synthesize `_0` — let the LIR handle the
        // 16-byte trait-obj layout".
        let ast_inner_name: Option<&str> = match &type_args[0].node {
            ast::Type::Named { name, .. } => Some(name.node.as_str()),
            _ => None,
        };
        let trait_via_ast = ast_inner_name
            .map(|n| {
                n.ends_with("_TraitObj")
                    || registry.get_type_def(&format!("{n}_TraitObj")).is_some()
            })
            .unwrap_or(false);
        if !trait_via_ast {
            let inner_type = mapper.map_ast_type(&type_args[0].node);
            fields.push(StructField {
                name: "_0".to_string(),
                type_id: inner_type,
            });
        }
    }

    // Box types need Move + Trivial("free") drop metadata for RAII.
    // ReadGuard[T] / WriteGuard[T] need Move + Trivial drop to release the pthread rwlock.
    // Collection types (Vector, Dict, etc.) get their own drop strategies.
    let metadata = if template.name.node == "Box" {
        // Mirror `register_collection_alias`'s Box arm: tag `is_box: true` so
        // downstream consumers reading `TypeRegistry::is_box(type_id)` see the
        // truth at this registration path (the AST-template-driven monomorph
        // path, distinct from the AST `Type::Named` recursion in
        // `map_ast_type_mut`).
        TypeMetadata {
            size: None,
            align: None,
            copy_semantics: CopySemantics::Resource,
            drop_strategy: DropStrategy::Trivial("free".to_string()),
            is_box: true,
            ..Default::default()
        }
    } else if matches!(template.name.node.as_str(), "ReadGuard" | "WriteGuard") {
        TypeMetadata {
            size: None,
            align: None,
            copy_semantics: CopySemantics::Resource,
            drop_strategy: DropStrategy::Trivial(format!("{mangled_name}__drop")),
            ..Default::default()
        }
    } else if template.name.node == "RWLock" {
        // RWLock[T] is declared as a `struct RWLock[T]` template in
        // `lib/std/sync.gg:36` (unlike Mutex, which is a pure builtin with no
        // template), so the ctor's `RWLock[int](v)` reaches THIS template-driven
        // monomorph path FIRST — before `map_ast_type_mut` / `register_collection_
        // alias` can stamp the per-mono drop wrapper. Without this arm RWLock
        // fell into the `else` (`compute_drop_strategy_for_struct` over its empty
        // monomorph fields → `drop: None`) and the single-owner handle LEAKED on
        // scope exit (Core #8 Inc-B). RWLock is SINGLE-OWNER (unique-free via
        // `gorget_rwlock_free`, NOT refcounted): `CopySemantics::Trivial` (owns, drops once) +
        // `{mangled}__drop` → `gorget_rwlock_free`, mirroring the Mutex semantics
        // and the ReadGuard/WriteGuard arm above. RWLock keeps `clone_fn = None`
        // (the default here), so `needs_param_drop`'s `clone_fn.is_some()` gate
        // (`ir/types.rs:537`) excludes its borrow-param — only the owner frees.
        TypeMetadata {
            size: None,
            align: None,
            copy_semantics: CopySemantics::Trivial,
            drop_strategy: DropStrategy::Trivial(format!("{mangled_name}__drop")),
            ..Default::default()
        }
    } else {
        // Tier 1c: coherence-at-construction for user generic structs.
        // Both blocker classes are now closed: per-mono Shared/Weak/
        // Channel/Mutex/RWLock/Guard wrapper emission walks
        // `recursive_drop_structs`/`recursive_drop_enums` in
        // `emit_types.rs`, and `populate_type_drop_fns` /
        // `populate_recursive_drop_structs` handle `GirType::FnPtr`
        // fields by emitting `gorget_closure_free` so iterator-chain
        // structs (`MapIter`, `FilterIter`, …) holding a `Callable f`
        // field drop their closure env on scope-exit.
        let (drop_strategy, copy_semantics) = registry.compute_drop_strategy_for_struct(&fields);
        TypeMetadata {
            drop_strategy,
            copy_semantics,
            ..Default::default()
        }
    };

    let type_def = TypeDef {
        name: mangled_name.to_string(),
        kind: TypeDefKind::Struct(StructDef { fields }),
        metadata,
    };

    registry.add_type_def(type_def);
    let type_id = registry.insert(GirType::Named(mangled_name.to_string()));
    mapper.named_types.insert(mangled_name.to_string(), type_id);

    // Thread[T]: record the typed payload channel at THIS mint site too.
    // `Thread` is declared as a `struct Thread[T]: pass` template in
    // lib/std/thread.gg, so annotated Thread types (locals, params, fields)
    // are minted by the generics pre-pass — which runs before function
    // lowering and bypasses the protocol branch in `map_ast_type_mut`.
    // Sibling of the protocol-branch write (`lowering/types.rs`) and the
    // thread_spawn-intrinsic write (`exprs/calls.rs`); all three record the
    // same name-deduped (tid → payload tid) pair.
    if template.name.node == "Thread" && !type_args.is_empty() {
        let payload = substitute_and_map_mut(mapper, registry, &type_args[0].node, &subs);
        mapper.thread_payload_types.insert(type_id, payload);
    }
}

/// Monomorphize a generic enum: create a TypeDef with substituted variant field types.
fn monomorphize_enum(
    template: &ast::EnumDef,
    type_args: &[Spanned<Type>],
    mangled_name: &str,
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
) {
    if mapper.named_types.contains_key(mangled_name) {
        return;
    }

    let subs = build_type_substitutions(template.generic_params.as_ref(), type_args);

    let mut variants: Vec<EnumVariant> = Vec::new();
    for v in &template.variants {
        let fields = match &v.node.fields {
            ast::VariantFields::Unit => vec![],
            ast::VariantFields::Tuple(types) => {
                let mut fs = Vec::new();
                for (i, t) in types.iter().enumerate() {
                    let field_type = substitute_and_map_mut(mapper, registry, &t.node, &subs);
                    fs.push(StructField {
                        name: format!("_{i}"),
                        type_id: field_type,
                    });
                }
                fs
            }
        };
        variants.push(EnumVariant {
            name: v.node.name.node.clone(),
            fields,
        });
    }

    let enum_category = match template.name.node.as_str() {
        "Option" => Some(EnumCategory::Option),
        "Result" => Some(EnumCategory::Result),
        _ => None,
    };
    // Tier 1c: compute drop metadata at construction for USER
    // generic enums. Option/Result skip the helper here —
    // upgrading them surfaces 17 runtime regressions in Option/Result
    // combinator fixtures (e.g., result_map.gg's map_err: a buffer
    // overread when a cross-type adapter result is byte-copied into a
    // wrongly-sized destination slot). The lowering's type inference
    // at the cross-type adapter result site needs to propagate the
    // NEW Result type (e.g., Result__int__int from map_err) to the
    // VarDecl's destination local — currently the dst local is
    // allocated with the OLD type. See
    // `docs/devbook/17-c-backend.md` (the Tier 1c cross-type adapter bug).
    //
    // After view-awareness was added to `validate_resource_moves`
    // (2026-05-11, this commit), the GIR-level validator probe shows
    // ONLY 2 genuine violations across the full suite when the
    // carve-out is removed — the other 15,632 prior "violations"
    // were SELF-HOST validator output (pre-existing Phase C
    // burn-down baseline, ~89k), not Rust validator output.
    // So Cluster 1 is far more tractable than initial estimates:
    // ~2 GIR violations + 17 runtime regressions = days of work,
    // not weeks.
    //
    // The post-hoc `upgrade_types_from_fields` runs before this pass
    // for non-monomorphic types, and Snag #27's
    // `make_option_type_def`/`make_result_type_def` cover the AST
    // pre-registration paths via `wrapper_metadata_for_payloads`.
    // Only the rare `monomorphize_enum`-first-sees-it case is left
    // stale here.
    // Tier 1c burn-down in progress — carve-out removed.
    let (drop_strategy, copy_semantics) = registry.compute_drop_strategy_for_enum(&variants);
    let metadata = TypeMetadata {
        enum_category,
        drop_strategy,
        copy_semantics,
        ..Default::default()
    };
    let type_def = TypeDef {
        name: mangled_name.to_string(),
        kind: TypeDefKind::Enum(EnumDef { variants }),
        metadata,
    };

    registry.add_type_def(type_def);
    let type_id = registry.insert(GirType::Named(mangled_name.to_string()));
    mapper.named_types.insert(mangled_name.to_string(), type_id);
}

/// Re-monomorphize a generic struct's fields after all user-generic names
/// have been registered in the first pass. This is the fix-up pass for
/// forward references (e.g. `TakeIter[int].inner: VectorIter[int]` where
/// `VectorIter[int]` wasn't yet in `named_types` on the first pass).
///
/// Builds a fresh TypeDef and registers it via `add_type_def` — since
/// `name_to_def` is a map, the new entry replaces the old one for lookup
/// purposes. Existing TypeIds that resolve to `GirType::Named(mangled_name)`
/// will now see the corrected fields.
fn remonomorphize_struct_fields(
    template: &ast::StructDef,
    type_args: &[Spanned<Type>],
    mangled_name: &str,
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
) {
    // Only re-mono if a first-pass TypeDef exists. If first pass skipped this
    // (e.g. collection alias branch), nothing to fix up.
    if registry.get_type_def(mangled_name).is_none() {
        return;
    }

    let subs = build_type_substitutions(template.generic_params.as_ref(), type_args);
    let mut fields: Vec<StructField> = Vec::new();
    for f in &template.fields {
        let field_type = substitute_and_map_mut(mapper, registry, &f.node.type_.node, &subs);
        fields.push(StructField {
            name: f.node.name.node.clone(),
            type_id: field_type,
        });
    }

    // Update the existing TypeDef in place — `add_type_def` would push a
    // duplicate entry, which the validator rejects.
    if let Some(td) = registry.get_type_def_mut(mangled_name) {
        td.kind = TypeDefKind::Struct(StructDef { fields });
    }
}

/// Re-monomorphize a generic enum's variant fields after all names are
/// registered. Mirror of `remonomorphize_struct_fields`.
fn remonomorphize_enum_fields(
    template: &ast::EnumDef,
    type_args: &[Spanned<Type>],
    mangled_name: &str,
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
) {
    if registry.get_type_def(mangled_name).is_none() {
        return;
    }
    let subs = build_type_substitutions(template.generic_params.as_ref(), type_args);
    let mut variants: Vec<EnumVariant> = Vec::new();
    for v in &template.variants {
        let fields = match &v.node.fields {
            ast::VariantFields::Unit => vec![],
            ast::VariantFields::Tuple(types) => {
                let mut fs = Vec::new();
                for (i, t) in types.iter().enumerate() {
                    let field_type = substitute_and_map_mut(mapper, registry, &t.node, &subs);
                    fs.push(StructField {
                        name: format!("_{i}"),
                        type_id: field_type,
                    });
                }
                fs
            }
        };
        variants.push(EnumVariant {
            name: v.node.name.node.clone(),
            fields,
        });
    }

    if let Some(td) = registry.get_type_def_mut(mangled_name) {
        td.kind = TypeDefKind::Enum(EnumDef { variants });
    }
}

/// Build a substitution map from generic param names to concrete AST types.
fn build_type_substitutions(
    generic_params: Option<&Spanned<ast::GenericParams>>,
    type_args: &[Spanned<Type>],
) -> Vec<(String, Type)> {
    let mut subs = Vec::new();
    if let Some(params) = generic_params {
        for (param, arg) in params.node.params.iter().zip(type_args.iter()) {
            let name = match &param.node {
                GenericParam::Type { name: s, .. } => s.node.clone(),
                GenericParam::Const { name, .. } => name.node.clone(),
            };
            subs.push((name, arg.node.clone()));
        }
    }
    subs
}

/// Build substitutions for an equip block (generic params come from the equipped type).
fn build_equip_type_substitutions(
    equip: &ast::EquipBlock,
    type_args: &[Spanned<Type>],
) -> Vec<(String, Type)> {
    // Generic params may come from the equip block itself or the equipped type
    if let Some(ref gp) = equip.generic_params {
        return build_type_substitutions(Some(gp), type_args);
    }
    // Fall back: extract params from the equipped type's generic args
    if let Type::Named { generic_args, .. } = &equip.type_.node {
        let mut subs = Vec::new();
        for (param_type, arg) in generic_args.iter().zip(type_args.iter()) {
            if let Type::Named { name, generic_args: inner } = &param_type.node {
                if inner.is_empty() {
                    // This is a bare type parameter name like "T"
                    subs.push((name.node.clone(), arg.node.clone()));
                }
            }
        }
        return subs;
    }
    Vec::new()
}

/// Substitute type parameters in an AST type and map to GIR TypeId.
fn substitute_and_map(
    mapper: &TypeMapper,
    ty: &Type,
    subs: &[(String, Type)],
) -> TypeId {
    let substituted = substitute_type(ty, subs);
    mapper.map_ast_type(&substituted)
}

/// Like substitute_and_map, but auto-registers new collection/Option/Result types.
/// Used in monomorphize_struct/enum where field types may reference derived collections.
fn substitute_and_map_mut(
    mapper: &mut TypeMapper,
    registry: &mut TypeRegistry,
    ty: &Type,
    subs: &[(String, Type)],
) -> TypeId {
    let substituted = substitute_type(ty, subs);
    mapper.map_ast_type_mut(&substituted, registry)
}

/// Lightweight AST-level type env used by per-call-site method-instance
/// discovery. Tracks variable → declared-or-inferred AST `Type`.
#[derive(Default, Clone)]
struct LocalTypeEnv {
    bindings: FxHashMap<String, Type>,
}

impl LocalTypeEnv {
    fn lookup(&self, name: &str) -> Option<&Type> {
        self.bindings.get(name)
    }
    fn bind(&mut self, name: String, ty: Type) {
        self.bindings.insert(name, ty);
    }
    fn snapshot(&self) -> FxHashMap<String, Type> {
        self.bindings.clone()
    }
    fn restore(&mut self, snapshot: FxHashMap<String, Type>) {
        self.bindings = snapshot;
    }
}

fn populate_env_from_params(env: &mut LocalTypeEnv, params: &[Spanned<ast::Param>]) {
    for p in params {
        if p.node.is_meta_op {
            continue;
        }
        env.bind(p.node.name.node.clone(), p.node.type_.node.clone());
    }
}

/// Extract a plain `Binding(name)` from a pattern; returns None for other
/// shapes (wildcards, destructures). Good enough for let bindings and simple
/// `for x in ...` loops — we don't handle destructuring let's in method-
/// instance discovery (very uncommon).
fn pattern_binding_name(p: &Spanned<ast::Pattern>) -> Option<String> {
    if let ast::Pattern::Binding(n) = &p.node {
        Some(n.clone())
    } else {
        None
    }
}

/// Extract `(base_name, type_args)` from an AST `Type::Named { name, generic_args }`.
fn extract_base_and_args(ty: &Type) -> Option<(String, Vec<Spanned<Type>>)> {
    match ty {
        Type::Named { name, generic_args } => Some((name.node.clone(), generic_args.clone())),
        // Unwrap ownership sigils — `Vector[T] &` has the same equip surface as `Vector[T]`.
        Type::Ref(inner) | Type::Owned(inner) => extract_base_and_args(&inner.node),
        _ => None,
    }
}

/// For a `for x in iterable` statement, peek at the iterable's declared type
/// and extract the element type. Handles the common shapes:
/// - `Vector[T]` / `Set[T]` → `T`
/// - `VectorIter[T]` / `TakeIter[T]` / `SkipIter[T]` / `ChainIter[T]` → `T`
/// - `MapIter[T, U, F]` → `U` (the output element type)
/// - `FilterIter[T, F]` → `T`
/// Unknown shapes return None; the loop body then doesn't get the element
/// binding but that's fine for our best-effort inference.
fn extract_iterator_element(ty: &Type) -> Option<Type> {
    match ty {
        Type::Named { name, generic_args } => {
            match name.node.as_str() {
                "Vector" | "Set" | "HashSet" | "Dict" | "HashMap"
                | "VectorIter" | "TakeIter" | "SkipIter" | "ChainIter" | "FilterIter" => {
                    generic_args.first().map(|a| a.node.clone())
                }
                // MapIter[T, U, F] yields U — use the second type arg.
                "MapIter" => generic_args.get(1).map(|a| a.node.clone()),
                _ => None,
            }
        }
        Type::Ref(inner) | Type::Owned(inner) => extract_iterator_element(&inner.node),
        _ => None,
    }
}

/// Mangle a method-instance target symbol.
///
/// Layout: `{mangled_type}__{method_name}{__ method_arg_mangle per arg}`.
/// Closure-typed method args collapse to `GorgetClosure` (uniform runtime
/// representation), so `map[int, int(int)]` and `map[int, bool(int)]`
/// share the same mangled symbol when their concrete U matches but F
/// differs — they would specialise the same body code anyway since all
/// closures share the 16-byte GorgetClosure ABI.
fn mangle_method_instance(
    mangled_type: &str,
    method_name: &str,
    method_type_args: &[Spanned<Type>],
) -> String {
    let mut result = format!("{mangled_type}__{method_name}");
    for targ in method_type_args {
        result.push_str("__");
        result.push_str(&mangle_type_for_name(&targ.node));
    }
    result
}

